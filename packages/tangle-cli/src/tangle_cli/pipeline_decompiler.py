"""Dehydrated pipeline YAML → deterministic ``python_pipeline`` source.

Reverses :mod:`tangle_cli.python_pipeline.emit` for the *dehydrated* shape
only, using the public authoring API. Every recovered value becomes an
``ast`` literal node, never interpolated text, and the result is proven by
recompiling it and comparing semantic digests.

Fails closed: anything this module cannot represent exactly raises
:class:`DecompileError` with a diagnostic code, and never echoes the value.
"""
