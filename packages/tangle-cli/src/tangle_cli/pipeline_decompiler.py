def decompile_pipeline(
    data: Mapping[str, Any],
    *,
    verify: bool = True,
) -> DecompileResult:
    """Return deterministic Python source reproducing ``data``.

    Args:
        data: A dehydrated pipeline dict (the shape ``pipelines compile``
            writes). Hydrated documents are refused.
        verify: Recompile the generated source in a temporary directory
            and require semantic-digest equality with ``data``.

    Raises:
        DecompileError: on any construct outside the supported subset, or
            when verification does not reproduce the input.
    """
    document = _require_mapping(data, "pipeline document")
    exempt_paths = assert_dehydrated_input(document)

    plan = _plan(document, exempt_paths)
    source = _render(plan)
    _assert_generated_source_is_safe(source)

    verified = False
    if verify:
        _verify_round_trip(source, document, plan.pipeline_name)
        verified = True

    return DecompileResult(
        source=source,
        pipeline_name=plan.pipeline_name,
        task_count=len(plan.tasks),
        verified=verified,
        normalizations=plan.normalizations,
    )


# A nested-graph boundary, as it appears in its parent's per-graph document.
# ``file://`` keeps the document schema-valid; every real leaf ref is a
# ``resolve://`` sidecar ref by the time codegen runs, so this cannot collide.
_SUBPIPELINE_MARKER = "file://./__decompiled_subpipeline__/"


@dataclass
class _GraphUnit:
    """One graph to emit as a ``@pipeline`` function."""

    function_name: str
    document: dict[str, Any]
    # task id -> child unit's function name, for each nested-graph boundary
    calls: dict[str, str]


def _split_graphs(pinned: Mapping[str, Any], root_function: str) -> tuple[_GraphUnit, list[_GraphUnit]]:
    """Give every nested graph, at any depth, its own unit -- deepest first.

    A boundary is replaced by a marker naming its child unit, so each unit is
    an ordinary per-graph document to plan and verify on its own. Identical
    graphs share one unit; a name already taken by different content gets a
    short content-digest suffix, so naming is deterministic.
    """
    by_digest: dict[str, _GraphUnit] = {}
    children: list[_GraphUnit] = []
    taken = {root_function}

    def visit(spec: Mapping[str, Any]) -> tuple[dict[str, Any], dict[str, str]]:
        document = copy.deepcopy(dict(spec))
        calls: dict[str, str] = {}
        tasks = document.get("implementation", {}).get("graph", {}).get("tasks") or {}
        for task_id, body in tasks.items():
            ref = body.get("componentRef") if isinstance(body, Mapping) else None
            if not isinstance(ref, Mapping) or not _is_graph_spec(ref.get("spec")):
                continue
            for key in ("isEnabled", "executionOptions"):
                if key in body:
                    raise DecompileError(
                        "unsupported-subgraph-task",
                        f"task {task_id} sets {key} on a nested graph. Tangle does "
                        "not apply it to graph-component tasks, so it has no "
                        "subpipeline(...) equivalent.",
                    )
            child = unit(ref["spec"])
            body["componentRef"] = {"url": f"{_SUBPIPELINE_MARKER}{child.function_name}.yaml"}
            calls[str(task_id)] = child.function_name
        return document, calls

    def unit(spec: Mapping[str, Any]) -> _GraphUnit:
        document, calls = visit(spec)
        digest = compute_spec_digest(document)
        if digest in by_digest:
            return by_digest[digest]
        name = _allocate_function_name(str(document.get("name") or ""), digest, taken)
        by_digest[digest] = made = _GraphUnit(name, document, calls)
        children.append(made)
        return made

    document, calls = visit(pinned)
    return _GraphUnit(root_function, document, calls), children


# Names a generated child function may never take: every authoring helper the
# module imports or an author would expect to (so a later hand edit cannot be
# shadowed either), and the prefixes of the locals inside every function body.
_RESERVED_GLOBAL_NAMES = frozenset({*_IMPORTS, "subpipeline", "task", "In", "Out"})
_LOCAL_PREFIXES = ("input_", "task_")


def _allocate_function_name(raw_name: str, digest: str, taken: set[str]) -> str:
    """The one allocator for generated child ``@pipeline`` function names.

    Keywords and builtins are already avoided by ``_python_identifier``. A name
    clashing with a helper or a local namespace is moved to ``graph_*``, and
    uniqueness is checked in a loop: another graph may literally be NAMED like
    a suffixed candidate. Deterministic, and independent of verification, so
    ``--no-verify`` can never emit a definition that silently replaces another.
    """
    base = _python_identifier(raw_name, prefix="subgraph")
    if base.startswith(_LOCAL_PREFIXES) or base in _RESERVED_GLOBAL_NAMES:
        base = f"graph_{base}"
    name, attempt = base, 1
    while name in taken or name in _RESERVED_GLOBAL_NAMES:
        name = f"{base}_{digest[:8]}" if attempt == 1 else f"{base}_{digest[:8]}_{attempt}"
        attempt += 1
    taken.add(name)
    return name


def _companion_module_name(output: Path) -> str | None:
    """``<stem>_subgraphs``, or None when that is not an importable module name.

    Deliberately not sanitized: mapping ``foo-bar`` and ``foo_bar`` to one
    companion would let either output silently replace the other's.
    """
    name = f"{output.stem}_subgraphs"
    # ASCII only: a non-ASCII module name can fail to import where the
    # filesystem stores a different Unicode normalization of the file name.
    return name if name.isascii() and name.isidentifier() and not keyword.iskeyword(name) else None


