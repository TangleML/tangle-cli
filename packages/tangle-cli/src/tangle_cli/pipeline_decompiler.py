def _runtime_sentinel_paths(document: Mapping[str, Any]) -> frozenset[str]:
    """Collect argument paths holding a legitimate ``{{...}}`` sentinel.

    Only *argument* string values qualify, and only when they carry no
    ``{%``/``{#`` token: those are compile-time Jinja, never runtime
    substitution, and ``raw()`` refuses them. Exempting such a value would
    hide a leaked template rather than preserve a placeholder, so they are
    left for the validator to reject.
    """
    paths: set[str] = set()

    def visit(container: Any, prefix: str) -> None:
        """Walk tasks at any depth, building full schema paths.

        Nested graphs only appear in hydrated input, where a sentinel is just
        as legitimate as at the root; collecting the root alone would refuse a
        document whose dehydrated equivalent is accepted.
        """
        if not isinstance(container, Mapping):
            return
        graph = container.get("graph")
        if not isinstance(graph, Mapping):
            return
        tasks = graph.get("tasks")
        if not isinstance(tasks, Mapping):
            return
        for task_id, body in tasks.items():
            if not isinstance(body, Mapping):
                continue
            task_path = f"{prefix}.graph.tasks.{task_id}"
            arguments = body.get("arguments")
            if isinstance(arguments, Mapping):
                for key, value in arguments.items():
                    if not isinstance(value, str) or _RUNTIME_SENTINEL not in value:
                        continue
                    if any(token in value for token in _COMPILE_TIME_TOKENS):
                        continue
                    paths.add(f"{task_path}.arguments.{key}")
            ref = body.get("componentRef")
            if isinstance(ref, Mapping):
                spec = ref.get("spec")
                if isinstance(spec, Mapping):
                    visit(
                        spec.get("implementation"),
                        f"{task_path}.componentRef.spec.implementation",
                    )

    visit(document.get("implementation"), "implementation")
    return frozenset(paths)


