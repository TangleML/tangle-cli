@dataclass
class _Plan:
    pipeline_name: str
    function_name: str
    description: str | None
    labels: dict[str, Any]
    annotations: dict[str, Any]
    inputs: list[dict[str, Any]]
    outputs: list[dict[str, Any]]
    output_values: dict[str, Any]
    tasks: list[tuple[str, dict[str, Any]]]
    names: dict[str, str]
    exempt_paths: frozenset[str]
    normalizations: tuple[str, ...] = ()
    input_names: set[str] = field(default_factory=set)
    # task id -> generated @pipeline function for a nested graph boundary
    subpipelines: dict[str, str] = field(default_factory=dict)
    # sidecar URL -> recovered @task name imported from the tasks package
    python_tasks: dict[str, str] = field(default_factory=dict)
    # sidecar URL -> unwrap parameter -> synthetic keys, for regrouping
    python_unwrap: dict[str, dict[str, tuple[str, ...]]] = field(default_factory=dict)
    # sidecar URL -> verified published digest, referenced directly
    digest_refs: dict[str, str] = field(default_factory=dict)


def _plan(document: Mapping[str, Any], exempt_paths: Collection[str]) -> _Plan:
    name = document.get("name")
    if not isinstance(name, str) or not name:
        raise DecompileError(
            "unsupported-document", "pipeline document has no usable 'name'."
        )

    metadata = _require_mapping(document.get("metadata") or {}, "metadata")
    labels = dict(_require_mapping(metadata.get("labels") or {}, "metadata.labels"))
    annotations = dict(
        _require_mapping(metadata.get("annotations") or {}, "metadata.annotations")
    )

    inputs = [
        _check_input(entry, index)
        for index, entry in enumerate(_as_list(document.get("inputs"), "inputs"))
    ]
    outputs = [
        _require_mapping(entry, f"outputs[{index}]")
        for index, entry in enumerate(_as_list(document.get("outputs"), "outputs"))
    ]
    for index, entry in enumerate(outputs):
        _check_io_annotations(entry, f"outputs[{index}]")

    graph = _require_mapping(
        _require_mapping(
            document.get("implementation") or {}, "implementation"
        ).get("graph")
        or {},
        "implementation.graph",
    )
    raw_tasks = _require_mapping(graph.get("tasks") or {}, "implementation.graph.tasks")
    output_values = _require_mapping(
        graph.get("outputValues") or {}, "implementation.graph.outputValues"
    )

    input_names = {str(entry["name"]) for entry in inputs}
    for task_id, body in raw_tasks.items():
        _check_task(str(task_id), _require_mapping(body, f"task {task_id!r}"))

    ordered = _topological_order(raw_tasks)
    names = _allocate_names(
        [str(entry["name"]) for entry in inputs], [task_id for task_id, _ in ordered]
    )

    normalizations: list[str] = []
    if any("default" in entry and "optional" not in entry for entry in inputs):
        normalizations.append(
            "N1: a graph input carrying 'default' but no explicit 'optional' "
            "is compared as optional: true, because graph_input() always "
            "writes optional alongside a default."
        )
    if _normalize_for_comparison(document) != _deep_copy(document):
        normalizations.append(
            "N2: an EMPTY block at a known optional location (metadata, "
            "inputs, outputs, outputValues, or a task's annotations, "
            "arguments or executionOptions) is compared as absent. Such a "
            "block declares nothing and the authoring API omits the key "
            "entirely, so it cannot survive a round trip. A block with any "
            "content is never dropped."
        )

    return _Plan(
        pipeline_name=name,
        function_name=_python_identifier(name, prefix="pipeline"),
        description=_optional_str(document.get("description"), "description"),
        labels=labels,
        annotations=annotations,
        inputs=inputs,
        outputs=outputs,
        output_values=dict(output_values),
        tasks=ordered,
        names=names,
        exempt_paths=frozenset(exempt_paths),
        normalizations=tuple(normalizations),
        input_names=input_names,
    )


