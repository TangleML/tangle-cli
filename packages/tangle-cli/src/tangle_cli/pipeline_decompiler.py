# Python task recovery: a static source transform. Nothing recovered is ever
# imported, executed, regenerated, compiled or hydrated here; Tangle does that
# later, when the maintainer compiles the generated script.

# Markers a leaf must carry, verbatim, to be recognised as generator output.
_PYTHON_MARKERS = {"cloud_pipelines.net": "true", "components new regenerate python-function-component": "true"}
# Annotations the generator writes itself: the markers this recovery consumes,
# and provenance Tangle re-derives from wherever the source is compiled.
_GENERATOR_ANNOTATIONS = frozenset({
    *_PYTHON_MARKERS,
    "python_original_code", "python_original_code_path", "python_dependencies",
    "tangle_cli_generation_function_name", "tangle_cli_generation_mode",
    "tangle_cli_generation_dependencies_from", "component_yaml_path",
    "git_relative_dir", "git_local_branch", "git_local_sha",
    "git_remote_url", "git_remote_branch", "git_remote_sha",
})


@dataclass(frozen=True)
class _PythonTask:
    """What ``@task`` needs to let Tangle rebuild one leaf from its own source."""

    function: str
    source: str
    # The recorded container image; for ``image_id`` sources, only what it
    # resolved to then -- compile re-resolves it in the maintainer's environment.
    image: str
    dependencies: tuple[str, ...]
    module_hint: str
    # Set when the source carries its own literal ``@task(...)``: it is then
    # re-exported as-is, never wrapped a second time.
    decorated: bool = False
    image_id: str | None = None
    dependencies_from: str | None = None
    # unwrap parameter -> its synthetic input keys, in spec input order
    unwrap: tuple[tuple[str, tuple[str, ...]], ...] = ()


def _has_python_markers(spec: Any) -> bool:
    annotations = _leaf_annotations(spec)
    return all(annotations.get(key) == value for key, value in _PYTHON_MARKERS.items()) and "python_original_code" in annotations


def _leaf_annotations(spec: Any) -> Mapping[str, Any]:
    metadata = spec.get("metadata") if isinstance(spec, Mapping) else None
    annotations = metadata.get("annotations") if isinstance(metadata, Mapping) else None
    return annotations if isinstance(annotations, Mapping) else {}


def _python_task(spec: Any) -> _PythonTask | None:
    """The ``@task`` form of a generator-made leaf, or None to keep it YAML.

    Static only, and conservative: anything ``@task`` cannot express (bundle
    mode, a resolve root, custom names or annotations, any decorator but one
    literal ``@task(...)``) or that cannot be checked from the source text
    alone stays a pinned YAML leaf.
    """
    import json

    from .component_from_func import _python_name_to_component_name, extract_docstring_metadata

    if not _has_python_markers(spec) or set(spec) - {"name", "description", "metadata", "inputs", "outputs", "implementation"}:
        return None
    annotations = _leaf_annotations(spec)
    source, function = annotations.get("python_original_code"), annotations.get("tangle_cli_generation_function_name")
    container = spec.get("implementation", {}).get("container") if isinstance(spec.get("implementation"), Mapping) else None
    image = container.get("image") if isinstance(container, Mapping) else None
    if (
        set(spec["metadata"]) != {"annotations"}
        # Exactly what the generator writes: anything else (env, fileOutputs,
        # ...) has no @task form and would be silently lost.
        or set(spec["implementation"]) != {"container"}
        or not isinstance(container, Mapping)
        or set(container) - {"image", "command", "args"}
        or not isinstance(source, str)
        or not isinstance(function, str)
        or function.startswith("_")
        or annotations.get("tangle_cli_generation_mode") != "inline"
        or not isinstance(image, str)
        or not image
    ):
        return None
    try:
        dependencies = json.loads(annotations.get("python_dependencies", "[]"))
        tree = ast.parse(source)
    except (ValueError, SyntaxError, TypeError):
        return None
    if not isinstance(dependencies, list) or not all(isinstance(d, str) for d in dependencies):
        return None
    bound = [node for name, node in _module_scope_bindings(tree.body) if name == function]
    if len(bound) != 1 or bound[0] not in tree.body or not isinstance(bound[0], ast.FunctionDef):
        return None
    # A relative import would resolve against the generated package instead.
    if _rebinds_dynamically(tree) or any(isinstance(n, ast.ImportFrom) and n.level for n in ast.walk(tree)):
        return None
    node = bound[0]
    config = _task_decorator(tree, node) if node.decorator_list else {"image": image}
    if config is None or not _task_config_is_supported(config, image):
        return None
    # The generator's own derivations, from the same text it would read.
    docstring = ast.get_docstring(node) or ""
    metadata = extract_docstring_metadata(docstring) if docstring else {}
    name = metadata.get("name") or _python_name_to_component_name(function)
    if spec.get("name") != name or spec.get("description") != (_docstring_description(docstring) or f"{name} component"):
        return None
    custom = {k: v for k, v in annotations.items() if k not in _GENERATOR_ANNOTATIONS}
    if custom != {k: v for k, v in metadata.items() if k not in ("name", "description")}:
        return None
    unwrap_names = config.get("unwrap", ())
    unwrap = _interface_matches(node, spec, (unwrap_names,) if isinstance(unwrap_names, str) else tuple(unwrap_names), tree)
    if unwrap is None:
        return None
    hint = PurePosixPath(str(annotations.get("python_original_code_path") or function)).stem
    return _PythonTask(
        function,
        source,
        image,
        tuple(dependencies),
        hint,
        decorated=bool(node.decorator_list),
        image_id=config.get("image_id"),
        dependencies_from=config.get("dependencies_from"),
        unwrap=tuple(unwrap.items()),
    )


# The literal ``@task(...)`` settings that map statically. Anything else (env,
# annotations, resolve_root, ...) keeps the leaf YAML.
_TASK_DECORATOR_KEYWORDS = frozenset({"image", "image_id", "mode", "dependencies_from", "unwrap"})
_UNWRAP_KEY = re.compile(r"[A-Za-z0-9_-]+")


def _task_decorator(tree: ast.Module, node: ast.FunctionDef) -> dict[str, Any] | None:
    """The literal keywords of the function's one ``@task(...)``, or None.

    Only the exact authoring form: a single call of ``task``, bound once, by a
    top-level unaliased ``from tangle_cli.python_pipeline import task``.
    """
    if len(node.decorator_list) != 1:
        return None
    decorator = node.decorator_list[0]
    if not (isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Name) and decorator.func.id == "task" and not decorator.args):
        return None
    bindings = [n for name, n in _module_scope_bindings(tree.body) if name == "task"]
    if not (
        len(bindings) == 1
        and bindings[0] in tree.body
        and isinstance(bindings[0], ast.ImportFrom)
        and bindings[0].module == "tangle_cli.python_pipeline"
        and bindings[0].level == 0
        # The very alias that binds ``task`` must import ``task``: one import
        # may also hold ``task as other, ref as task``.
        and any(alias.name == "task" and (alias.asname or alias.name) == "task" for alias in bindings[0].names)
    ):
        return None
    config: dict[str, Any] = {}
    for keyword_ in decorator.keywords:
        if keyword_.arg not in _TASK_DECORATOR_KEYWORDS or keyword_.arg in config:
            return None
        try:
            config[keyword_.arg] = ast.literal_eval(keyword_.value)
        except (ValueError, TypeError, SyntaxError, MemoryError, RecursionError):
            return None
    return config


def _task_config_is_supported(config: Mapping[str, Any], recorded_image: str) -> bool:
    """``image`` must equal the recorded one; ``image_id`` is kept as source
    intent (compile resolves it). Mode inline, dependencies a safe relative
    ``.toml`` path, unwrap a set of names."""
    image, image_id = config.get("image"), config.get("image_id")
    if (image is None) == (image_id is None):
        return False
    if image is not None and image != recorded_image:
        return False
    if image_id is not None and not (isinstance(image_id, str) and image_id):
        return False
    if config.get("mode", "inline") != "inline":
        return False
    dependencies_from = config.get("dependencies_from")
    if dependencies_from is not None and not _safe_relative_toml(dependencies_from):
        return False
    unwrap = config.get("unwrap", ())
    unwrap = (unwrap,) if isinstance(unwrap, str) else unwrap
    return (
        isinstance(unwrap, (list, tuple))
        and all(isinstance(u, str) and u and u not in _RESERVED_CALL_KEYWORDS for u in unwrap)
        and len(set(unwrap)) == len(unwrap)
    )


def _safe_relative_toml(value: Any) -> bool:
    if not isinstance(value, str) or not value or "\\" in value:
        return False
    path = PurePosixPath(value)
    # A ``*.py`` directory would collide with the module directory's own
    # ``__init__.py`` / ``<module>.py`` files.
    return (
        not path.is_absolute()
        and bool(path.parts)
        and ".." not in path.parts
        and path.suffix == ".toml"
        # casefold: a case-insensitive filesystem treats __INIT__.PY as __init__.py
        and not any(part.casefold().endswith(".py") for part in path.parts[:-1])
    )


def _module_scope_bindings(statements: Sequence[ast.stmt]) -> Iterator[tuple[str, ast.AST]]:
    """Every module-scope binding, through if/try/for/with/match bodies, but
    not into function or class scopes. Over-approximate on purpose: a name
    bound inside a comprehension is counted too, and only costs a conversion."""
    for statement in statements:
        if isinstance(statement, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            yield statement.name, statement
            # Everything but the body is evaluated at module scope: decorators,
            # bases and keywords, parameter defaults and annotations, returns.
            for name, value in ast.iter_fields(statement):
                if name != "body":
                    for child in value if isinstance(value, list) else [value]:
                        if isinstance(child, ast.AST):
                            yield from _expression_bindings(child, statement)
            continue
        if isinstance(statement, (ast.Import, ast.ImportFrom)):
            for alias in statement.names:
                yield (alias.asname or alias.name).split(".")[0], statement
            continue
        for child in ast.iter_child_nodes(statement):
            if isinstance(child, ast.stmt):
                yield from _module_scope_bindings([child])
            elif isinstance(child, ast.ExceptHandler):
                if child.name:
                    yield child.name, statement
                if child.type:
                    yield from _expression_bindings(child.type, statement)
                yield from _module_scope_bindings(child.body)
            elif isinstance(child, ast.match_case):
                yield from _expression_bindings(child.pattern, statement)
                if child.guard:
                    yield from _expression_bindings(child.guard, statement)
                yield from _module_scope_bindings(child.body)
            else:
                yield from _expression_bindings(child, statement)


def _expression_bindings(node: ast.AST, owner: ast.AST) -> Iterator[tuple[str, ast.AST]]:
    for child in ast.walk(node):
        if isinstance(child, ast.Name) and isinstance(child.ctx, (ast.Store, ast.Del)):
            yield child.id, owner
        elif isinstance(child, (ast.MatchAs, ast.MatchStar)) and child.name:
            yield child.name, owner
        elif isinstance(child, ast.MatchMapping) and child.rest:
            yield child.rest, owner


# Ways to rebind a module global without a binding statement. Seeing any of
# them anywhere means the static contract cannot hold.
_DYNAMIC_REBINDING = frozenset({"globals", "vars", "exec", "eval", "setattr", "delattr", "__import__", "__dict__", "modules"})


def _rebinds_dynamically(tree: ast.AST) -> bool:
    return any(
        (isinstance(n, ast.Name) and n.id in _DYNAMIC_REBINDING)
        or (isinstance(n, ast.Attribute) and n.attr in _DYNAMIC_REBINDING)
        or isinstance(n, (ast.Global, ast.Nonlocal))
        # Binds names only importing the module could list.
        or (isinstance(n, ast.ImportFrom) and any(alias.name == "*" for alias in n.names))
        for n in ast.walk(tree)
    )


def _docstring_description(docstring: str) -> str | None:
    """The generator's description: the docstring summary, without Metadata."""
    import docstring_parser

    description = docstring_parser.parse(docstring).description
    if not description:
        return None
    lines = []
    for line in description.split("\n"):
        if line.strip().lower() == "metadata:":
            break
        lines.append(line)
    return "\n".join(lines).strip() or None


def _interface_matches(
    node: ast.FunctionDef, spec: Mapping[str, Any], unwrap: Sequence[str] = (), tree: ast.Module | None = None
) -> dict[str, tuple[str, ...]] | None:
    """Unwrap parameter -> synthetic keys when every input/output is accounted
    for, else None.

    Names only: types come from annotations only evaluating the source could
    resolve. A fixed parameter names exactly one input/output; every other
    input must be exactly one unwrap parameter's ``<param>__<key>`` (keys as
    ``@task`` allows). Outputs no parameter names are allowed only for a
    function with a return annotation, which the generator turns into outputs.
    """
    arguments = node.args
    if arguments.vararg or arguments.kwarg:
        return None
    names = []
    # The keys the generator writes per input/output; any other (annotations,
    # ...) has no @task form and would be lost.
    for kind, written in (("inputs", {"name", "type", "description", "default", "optional"}), ("outputs", {"name", "type", "description"})):
        entries = spec.get(kind) or []
        if not isinstance(entries, list) or not all(
            isinstance(e, Mapping) and isinstance(e.get("name"), str) and not set(e) - written for e in entries
        ):
            return None
        names.append([e["name"] for e in entries])
    inputs, outputs = names
    if len(set(inputs + outputs)) != len(inputs + outputs):
        return None
    parameters = {p.arg: p for p in (*arguments.posonlyargs, *arguments.args, *arguments.kwonlyargs)}
    for name in unwrap:
        # Unwrap needs a dict parameter, and flattening leaves no input of its
        # own (an output may share its name: another parameter's ``<name>_path``).
        annotation = parameters[name].annotation if name in parameters else None
        if name not in parameters or name in inputs or not _is_dict_annotation(annotation, tree):
            return None
    claimed: set[str] = set()
    for parameter in parameters:
        if parameter in unwrap:
            continue
        candidates = {parameter, *(parameter[: -len(s)] for s in ("_path", "_file") if parameter.endswith(s))}
        hits = candidates & set(inputs + outputs)
        if len(hits) != 1 or hits & claimed:
            return None
        claimed |= hits
    synthetic: dict[str, list[str]] = {name: [] for name in unwrap}
    for name in inputs:
        owners = [u for u in unwrap if name.startswith(f"{u}__") and _UNWRAP_KEY.fullmatch(name[len(u) + 2:])]
        if name in claimed:
            if owners:
                return None  # a fixed input that also reads as synthetic is ambiguous
            continue
        if len(owners) != 1:
            return None
        synthetic[owners[0]].append(name[len(owners[0]) + 2:])
    if any(not keys for keys in synthetic.values()):
        return None  # @task refuses an empty unwrap dict
    if not (set(outputs) <= claimed or node.returns is not None):
        return None
    return {name: tuple(keys) for name, keys in synthetic.items()}


def _is_dict_annotation(annotation: ast.expr | None, tree: ast.Module | None) -> bool:
    """None, ``dict`` / ``dict[...]``, or ``Dict`` / ``Dict[...]`` from a
    top-level ``from typing import Dict`` -- each name provably unrebound."""
    if annotation is None:
        return True
    base = annotation.value if isinstance(annotation, ast.Subscript) else annotation
    if not isinstance(base, ast.Name) or base.id not in ("dict", "Dict"):
        return False
    bindings = [n for name, n in _module_scope_bindings(tree.body) if name == base.id] if tree is not None else []
    if base.id == "dict":
        return not bindings
    return (
        len(bindings) == 1
        and bindings[0] in tree.body  # type: ignore[union-attr]
        and isinstance(bindings[0], ast.ImportFrom)
        and bindings[0].module == "typing"
        and bindings[0].level == 0
        and any(alias.name == "Dict" and alias.asname is None for alias in bindings[0].names)
    )


def _tasks_package_name(output: Path) -> str | None:
    """``<stem>_tasks``, under the same one-to-one rule as the companion."""
    name = f"{output.stem}_tasks"
    return name if name.isascii() and name.isidentifier() and not keyword.iskeyword(name) else None


@dataclass(frozen=True)
class _EmittedTask:
    name: str
    module: str
    task: _PythonTask


def _allocate_python_tasks(recovered: Mapping[str, _PythonTask], taken: set[str]) -> dict[str, _EmittedTask]:
    """url -> emitted task. One module per distinct (source, function, config).

    Task names share the module namespace with every generated function, via
    the same allocator -- and so do the subpackage names: importing
    ``.<module>`` binds ``<module>`` on the package, which would replace a task
    exported under that name.
    """
    import json

    by_key: dict[str, _EmittedTask] = {}
    emitted: dict[str, _EmittedTask] = {}
    for url in sorted(recovered):
        task = recovered[url]
        key = json.dumps([
            task.source, task.function, task.image, task.dependencies,
            task.decorated, task.image_id, task.dependencies_from, task.unwrap,
        ])
        if key not in by_key:
            digest = hashlib.sha256(key.encode("utf-8")).hexdigest()
            by_key[key] = _EmittedTask(
                _allocate_function_name(task.function, digest, taken),
                _allocate_function_name(task.module_hint, digest, taken),
                task,
            )
        emitted[url] = by_key[key]
    return emitted


_TASKS_HEADER = (
    "Generated by `tangle sdk pipelines decompile`.\n\n"
    "Each subpackage holds python_original_code recovered byte-for-byte from\n"
    "the input pipeline YAML. The decompiler never imported or ran it;\n"
    "`tangle sdk pipelines compile` imports it, and hydrate/submit/run execute\n"
    "it to rebuild each component. Review it before compiling.\n"
)


def _task_module(emitted: _EmittedTask) -> str:
    """``<module>.<module>``: each recovered module has its own directory, so a
    source's own relative ``dependencies_from`` cannot collide with another's."""
    return f"{emitted.module}.{emitted.module}"


def _dependencies_path(emitted: _EmittedTask) -> str:
    """Where the recorded dependencies go, relative to the module's directory.

    A wrapped function names it explicitly; a decorated source's own literal
    ``dependencies_from`` is honoured; with none, ``<module>.toml`` is the file
    the generator's own discovery picks first, pinning the recorded list
    rather than whatever pyproject.toml it would otherwise find.
    """
    if not emitted.task.decorated:
        return f"{emitted.module}.deps.toml"
    return emitted.task.dependencies_from or f"{emitted.module}.toml"


def _render_tasks_package(tasks: Sequence[_EmittedTask]) -> str:
    """``__init__.py``: a decorated source is re-exported as it is; anything
    else gets one ``task(...)`` wrapper."""
    body: list[ast.stmt] = []
    if any(not emitted.task.decorated for emitted in tasks):
        body.append(ast.ImportFrom(module="tangle_cli.python_pipeline", names=[ast.alias(name="task", asname=None)], level=0))
    wrappers: list[ast.stmt] = []
    for index, emitted in enumerate(tasks):
        alias = emitted.name if emitted.task.decorated else f"_recovered_{index}"
        body.append(ast.ImportFrom(module=_task_module(emitted), names=[ast.alias(name=emitted.task.function, asname=alias)], level=1))
        if emitted.task.decorated:
            continue
        keywords = [
            ast.keyword(arg="image", value=_literal(emitted.task.image)),
            ast.keyword(arg="mode", value=_literal("inline")),
            # Always, even when empty: pins "no dependencies" rather than let
            # the generator discover some unrelated pyproject.toml.
            ast.keyword(arg="dependencies_from", value=_literal(_dependencies_path(emitted))),
        ]
        wrappers.append(
            ast.Assign(
                targets=[ast.Name(id=emitted.name, ctx=ast.Store())],
                value=ast.Call(
                    func=ast.Call(func=ast.Name(id="task", ctx=ast.Load()), args=[], keywords=keywords),
                    args=[ast.Name(id=alias, ctx=ast.Load())],
                    keywords=[],
                ),
                type_comment=None,
            )
        )
    module = ast.Module(body=[*body, *wrappers], type_ignores=[])
    ast.fix_missing_locations(module)
    return f'"""{_TASKS_HEADER}"""\n{ast.unparse(module)}\n'


def _dependencies_toml(dependencies: Sequence[str]) -> str:
    return "[project]\ndependencies = [" + ", ".join(_toml_string(d) for d in dependencies) + "]\n"


def _toml_string(value: str) -> str:
    """A TOML basic string. Not ``json.dumps``: its surrogate-pair escapes for
    non-BMP characters are not Unicode scalar values, which TOML rejects."""
    escaped = []
    for character in value:
        if character in '"\\':
            escaped.append("\\" + character)
        elif ord(character) < 0x20 or ord(character) == 0x7F:
            escaped.append(f"\\u{ord(character):04X}")
        else:
            escaped.append(character)
    return '"' + "".join(escaped) + '"'


def _write_tasks_package(directory: Path, tasks: Sequence[_EmittedTask]) -> None:
    directory.mkdir()
    (directory / "__init__.py").write_text(_render_tasks_package(tasks), encoding="utf-8")
    for emitted in tasks:
        module = directory / emitted.module
        module.mkdir()
        (module / "__init__.py").write_text("", encoding="utf-8")
        (module / f"{emitted.module}.py").write_bytes(emitted.task.source.encode("utf-8"))
        dependencies = module / _dependencies_path(emitted)
        dependencies.parent.mkdir(parents=True, exist_ok=True)
        dependencies.write_text(_dependencies_toml(emitted.task.dependencies), encoding="utf-8")


def _assert_tasks_package(directory: Path, tasks: Sequence[_EmittedTask]) -> None:
    """Static checks of what was written: text, imports, wrappers, dependencies."""
    try:
        import tomllib
    except ModuleNotFoundError:  # pragma: no cover - Python 3.10
        import tomli as tomllib  # type: ignore[no-redef]

    modules = {_task_module(emitted) for emitted in tasks}
    tree = ast.parse((directory / "__init__.py").read_text(encoding="utf-8"))
    imported = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and not (
            (node.module == "tangle_cli.python_pipeline" and node.level == 0) or (node.module in modules and node.level == 1)
        ):
            raise DecompileError("codegen-unsafe-node", "the generated tasks package imports an unexpected module.")
        if not isinstance(node, _ALLOWED_NODES):
            raise DecompileError("codegen-unsafe-node", f"the generated tasks package contains an unexpected {type(node).__name__} node.")
        if isinstance(node, ast.ImportFrom) and node.level == 1:
            imported[node.names[0].asname] = (node.module, node.names[0].name)
    wrapped = {
        node.targets[0].id: (imported[node.value.args[0].id], {k.arg: ast.literal_eval(k.value) for k in node.value.func.keywords})
        for node in tree.body
        if isinstance(node, ast.Assign)
    }
    for emitted in tasks:
        task = emitted.task
        origin = (_task_module(emitted), task.function)
        if task.decorated:
            ok = imported.get(emitted.name) == origin and emitted.name not in wrapped
        else:
            ok = wrapped.get(emitted.name) == (origin, {"image": task.image, "mode": "inline", "dependencies_from": _dependencies_path(emitted)})
        module = directory / emitted.module
        source = (module / f"{emitted.module}.py").read_bytes()
        dependencies = tomllib.loads((module / _dependencies_path(emitted)).read_text(encoding="utf-8"))
        if (
            not ok
            or (module / "__init__.py").read_bytes()
            or source != task.source.encode("utf-8")
            or dependencies.get("project", {}).get("dependencies") != list(task.dependencies)
            or not any(isinstance(n, ast.FunctionDef) and n.name == task.function for n in ast.parse(source).body)
        ):
            raise DecompileError(
                "verification-invalid-output",
                "the generated tasks package does not carry exactly the recorded "
                "source, function, image and dependencies.",
            )


def _decompile_units(
    root: _GraphUnit,
    children: list[_GraphUnit],
    companion: str,
    *,
    verify: bool,
    python_tasks: Mapping[str, _EmittedTask] | None = None,
    tasks_package: str | None = None,
    digest_refs: Mapping[str, str] | None = None,
) -> tuple[DecompileResult, str | None]:
    """Render the root module and, when there are nested graphs, its companion.

    Gate (b) verifies the all-YAML-leaf form. Recovered Python tasks are then
    substituted, and the result is checked statically to differ from that
    verified form only at those call sites: nothing recovered is ever run here.
    """
    plans = []
    for graph in (root, *children):
        plan = _plan(graph.document, assert_dehydrated_input(graph.document))
        plan.function_name = graph.function_name
        plan.subpipelines = dict(graph.calls)
        plans.append(plan)
    root_plan, child_plans = plans[0], plans[1:]
    owner = companion if child_plans else None

    def render(package: str | None) -> tuple[str, str | None]:
        companion_source = _render_module(child_plans, tasks_package=package) if child_plans else None
        root_source = _render_module([root_plan], owner, tuple(sorted(set(root.calls.values()))), package)
        _assert_generated_source_is_safe(root_source, owner, package)
        if companion_source is not None:
            _assert_generated_source_is_safe(companion_source, package)
        return root_source, companion_source

    root_source, companion_source = render(None)
    if verify:
        _verify_units(root_source, companion_source, companion, [root, *children])
    if python_tasks or digest_refs:
        python_tasks = python_tasks or {}
        names = {url: emitted.name for url, emitted in python_tasks.items()}
        unwraps = {url: dict(emitted.task.unwrap) for url, emitted in python_tasks.items() if emitted.task.unwrap}
        for plan in plans:
            plan.python_tasks = names
            plan.python_unwrap = unwraps
            plan.digest_refs = dict(digest_refs or {})
        verified = (root_source, companion_source)
        root_source, companion_source = render(tasks_package if python_tasks else None)
        unwrap_by_name = {names[url]: frozenset(unwrap) for url, unwrap in unwraps.items()}
        for before, after in zip(verified, (root_source, companion_source)):
            if before is not None:
                _assert_only_task_substitutions(
                    before, after or "", names, tasks_package or "", unwrap_by_name, digest_refs or {}
                )
    return (
        DecompileResult(
            source=root_source,
            pipeline_name=root_plan.pipeline_name,
            task_count=len(root_plan.tasks),
            verified=verify,
            normalizations=tuple(dict.fromkeys(note for plan in plans for note in plan.normalizations)),
        ),
        companion_source,
    )


def _verify_units(root_source: str, companion_source: str | None, companion: str, units: list[_GraphUnit]) -> None:
    """Gate (b) per graph: each function must trace back to exactly its unit.

    A boundary traces as a ``subpipeline://pending`` task; it is mapped back to
    the marker naming the child it actually calls, so calling the wrong child
    fails the comparison too. The root imports its companion by NAME, which
    caches it in ``sys.modules``; it is evicted afterwards, or a later run in
    this process would import this run's stale companion instead of its own.
    """
    import sys

    with tempfile.TemporaryDirectory() as tmp:
        root_path = Path(tmp) / "decompiled_pipeline.py"
        root_path.write_text(root_source, encoding="utf-8")
        companion_path = Path(tmp) / f"{companion}.py"
        if companion_source is not None:
            companion_path.write_text(companion_source, encoding="utf-8")
        try:
            for index, graph in enumerate(units):
                module_path = root_path if index == 0 else companion_path
                rebuilt, exempt_paths, calls = _trace_function(module_path, graph.function_name)
                tasks = rebuilt.get("implementation", {}).get("graph", {}).get("tasks", {})
                for task_id, child in calls:
                    if task_id in tasks:
                        tasks[task_id]["componentRef"] = {"url": f"{_SUBPIPELINE_MARKER}{child}.yaml"}
                _compare_rebuilt(rebuilt, exempt_paths, graph.document)
        finally:
            sys.modules.pop(companion, None)


def _assert_only_task_substitutions(
    before: str,
    after: str,
    names: Mapping[str, str],
    package: str,
    unwrap: Mapping[str, frozenset[str]] | None = None,
    digests: Mapping[str, str] | None = None,
) -> None:
    """``after`` must be the verified ``before`` with each converted
    ``ref(url=...)`` replaced by its task name, plus that task import -- and,
    for an unwrap task, its flattened arguments regrouped into dicts, which
    are flattened back here before comparing (keyword order aside)."""
    unwrap = unwrap or {}

    class Substitute(ast.NodeTransformer):
        def visit_Call(self, node: ast.Call) -> ast.AST:
            self.generic_visit(node)
            url = _ref_url(node)
            if url is not None and url in names:
                return ast.Name(id=names[url], ctx=ast.Load())
            if url is not None and url in (digests or {}):
                return _digest_ref(digests[url])  # type: ignore[index]
            return node

    class Flatten(ast.NodeTransformer):
        def __init__(self, regroup: bool) -> None:
            self.regroup = regroup

        def visit_Call(self, node: ast.Call) -> ast.AST:
            self.generic_visit(node)
            params = unwrap.get(_call_root(node) or "")
            if params is None:
                return node
            keywords = []
            for item in node.keywords:
                if self.regroup and item.arg in params and isinstance(item.value, ast.Dict):
                    for key, value in zip(item.value.keys, item.value.values):
                        flat = f"{item.arg}__{key.value}" if isinstance(key, ast.Constant) else ""
                        keywords.append(
                            ast.keyword(arg=flat, value=value)
                            if flat.isidentifier() and not keyword.iskeyword(flat)
                            else ast.keyword(arg=None, value=ast.Dict(keys=[ast.Constant(value=flat)], values=[value]))
                        )
                else:
                    keywords.append(item)
            node.keywords = sorted(keywords, key=lambda k: k.arg or ast.dump(k.value))
            return node

    expected = Flatten(regroup=False).visit(Substitute().visit(ast.parse(before)))
    actual = ast.parse(after)
    actual.body = [n for n in actual.body if not (isinstance(n, ast.ImportFrom) and n.module == package)]
    actual = Flatten(regroup=True).visit(actual)
    # The header docstring says which components are not proven; nothing else
    # may differ.
    for tree in (expected, actual):
        tree.body = [n for i, n in enumerate(tree.body) if not (i == 0 and isinstance(n, ast.Expr))]
    if ast.dump(expected) != ast.dump(actual):
        raise DecompileError(
            "verification-invalid-output",
            "substituting recovered Python tasks changed more than their call sites.",
        )


def _digest_ref(digest: str) -> ast.Call:
    return ast.Call(func=ast.Name(id="ref", ctx=ast.Load()), args=[], keywords=[ast.keyword(arg="digest", value=_literal(digest))])


def _call_root(node: ast.AST) -> str | None:
    """The name a ``name.named(...)...(...)`` call chain starts from."""
    while isinstance(node, (ast.Call, ast.Attribute)):
        node = node.func if isinstance(node, ast.Call) else node.value
    return node.id if isinstance(node, ast.Name) else None


def _unwrap_calls_fit(pinned: Mapping[str, Any], recovered: dict[str, _PythonTask]) -> None:
    """Keep an unwrap leaf YAML unless EVERY task using it passes exactly its
    synthetic inputs: ``@task`` derives them from the call-site dict, so a
    missing, extra or bare one would compile to a different component."""

    def visit(document: Mapping[str, Any]) -> None:
        tasks = document.get("implementation", {}).get("graph", {}).get("tasks")
        for body in (tasks or {}).values() if isinstance(tasks, Mapping) else ():
            ref = body.get("componentRef") if isinstance(body, Mapping) else None
            if not isinstance(ref, Mapping):
                continue
            if _is_graph_spec(ref.get("spec")):
                visit(ref["spec"])
                continue
            task = recovered.get(ref.get("url"))
            if task is None or not task.unwrap:
                continue
            arguments = {str(k) for k in (body.get("arguments") or {})}
            for name, keys in task.unwrap:
                synthetic = {f"{name}__{key}" for key in keys}
                if name in arguments or {a for a in arguments if a.startswith(f"{name}__")} != synthetic:
                    recovered.pop(ref["url"], None)
                    break

    visit(pinned)


def decompile_pipeline_file(
    pipeline_path: Path,
    output: Path,
    *,
    verify: bool = True,
    client: Any = None,
    python_tasks: bool = True,
    include_local_fallbacks: bool = False,
) -> DecompileResult:
    """Decompile ``pipeline_path`` and write the source to ``output``.

    Accepts hydrated or dehydrated pipeline YAML. Every graph becomes Python:
    the root in ``output``, each nested graph as a ``@pipeline`` in the
    companion ``<stem>_subgraphs.py``. Every leaf component is resolved and
    re-pinned through the ``<stem>.leaves.yaml`` sidecar, with a local copy
    in ``<stem>.leaves/``. All products are staged and gated before any is
    published, and any failure aborts the whole operation.

    With ``python_tasks`` (the default), a leaf the Python component generator
    made, whose source is recorded in full, becomes a ``@task`` in
    ``<stem>_tasks/`` instead: a static source transform that never runs that
    source. ``python_tasks=False`` keeps every leaf a digest-pinned YAML leaf.

    A leaf the component library verified is referenced by its published
    digest alone, so hydration needs the library; ``include_local_fallbacks``
    also keeps a local copy behind each one, for offline-resilient output. A
    leaf with no published digest is always written locally.

    ``output`` is always replaced, and a stale components directory from a
    previous run of the same output is replaced wholesale rather than merged.
    """
    document = _parse_input(pipeline_path)
    if not isinstance(document, Mapping):
        raise DecompileError(
            "unsupported-document",
            f"{pipeline_path} does not contain a YAML mapping.",
        )

    # Classify and validate the ORIGINAL under its own contract, before
    # resolution can launder an unsupported shape into a supported one.
    assert_supported_input(document)

    # Lexically absolute, never ``resolve()``: resolving would follow a
    # symlink at the output path and overwrite its target, where every other
    # write here replaces the link itself.
    output = Path(os.path.abspath(output))
    # Never ``<stem>.components*``: ``compile <stem>.py -o <stem>.yaml`` writes
    # its own ``@task`` sidecar there, and would replace this one. An existing
    # ``.components*`` artifact is never touched, as it may be the compiler's.
    assets_name = f"{output.stem}.leaves"
    sidecar_name = f"{output.stem}.leaves.yaml"
    companion = _companion_module_name(output)
    tasks_package = _tasks_package_name(output)
    # Stage the script, its resolve sidecar and its assets in the layout they
    # will be published into, so the relative URLs written now are the ones
    # that will be correct after publication.
    with _staging_directory(output.parent) as stage:
        canonical = canonicalize_components(
            document,
            base_dir=pipeline_path.parent,
            components_dir=stage / assets_name,
            output_file=stage / output.name,
            client=client,
            sidecar_name=sidecar_name,
        )
        # Gate (a): pinning preserved the pipeline.
        assert_pinning_preserved(
            canonical, script_dir=stage, sidecar=sidecar_name, client=client
        )
        # Every nested graph becomes its own @pipeline in the companion module;
        # gate (b) then proves each generated function reproduces its graph.
        root, children = _split_graphs(
            canonical.pinned, _python_identifier(str(canonical.pinned.get("name") or ""), prefix="pipeline")
        )
        if children and companion is None:
            raise DecompileError(
                "unsupported-output-name",
                "this pipeline has nested graphs, which are written to a "
                "companion <stem>_subgraphs.py that the script imports by name, "
                f"so the output name must make a valid Python module name; "
                f"{output.name!r} does not.",
            )
        recovered, candidates = _recover_python_tasks(canonical) if python_tasks else ({}, _count_python_candidates(canonical))
        # Before the name check: it applies only when something still converts.
        _unwrap_calls_fit(canonical.pinned, recovered)
        if recovered and tasks_package is None:
            raise DecompileError(
                "unsupported-output-name",
                "this pipeline has Python components, which are written to a "
                "<stem>_tasks package that the script imports by name, so the "
                f"output name must make a valid Python module name; {output.name!r} "
                "does not. Rename the output, or pass --no-python-tasks.",
            )
        emitted = _allocate_python_tasks(recovered, {root.function_name, *(c.function_name for c in children)})
        # After both gates, which ran on the portable form: every digest here
        # was verified online and every copy offline. Dropping the copy is a
        # static substitution, checked like the Python tasks.
        digests = {} if include_local_fallbacks else _verified_digests(stage / sidecar_name, sidecar_name, set(emitted))
        result, companion_source = _decompile_units(
            root, children, companion or "", verify=verify, python_tasks=emitted, tasks_package=tasks_package,
            digest_refs=digests,
        )

        staged_script = stage / output.name
        staged_script.write_text(result.source, encoding="utf-8")
        if companion_source is not None:
            (stage / f"{companion}.py").write_text(companion_source, encoding="utf-8")
        if emitted:
            distinct = list({e.name: e for e in emitted.values()}.values())
            _write_tasks_package(stage / str(tasks_package), distinct)
            _assert_tasks_package(stage / str(tasks_package), distinct)
        if emitted or digests:
            _prune_sidecar(stage, sidecar_name, set(emitted) | set(digests))
            _assert_remaining_leaves_resolve(stage, sidecar_name, [result.source, companion_source or ""])
        staged_assets = stage / assets_name
        # Recursive: subgraphs are extracted into their own subdirectory.
        files = (
            tuple(
                sorted(
                    p.relative_to(staged_assets).as_posix()
                    for p in staged_assets.rglob("*")
                    if p.is_file()
                )
            )
            if staged_assets.is_dir()
            else ()
        )

        published = _publish(
            staged_script,
            output,
            [
                # Listed even when unused, so a stale companion is removed.
                *([(stage / f"{companion}.py", output.parent / f"{companion}.py")] if companion else []),
                *([(stage / tasks_package, output.parent / tasks_package)] if tasks_package else []),
                (stage / sidecar_name, output.parent / sidecar_name),
                (staged_assets, output.parent / assets_name),
            ],
        )

    return replace(
        result,
        output_path=output,
        components_dir=output.parent / assets_name if output.parent / assets_name in published else None,
        component_files=files,
        resolve_config=output.parent / sidecar_name if output.parent / sidecar_name in published else None,
        subgraph_module=output.parent / f"{companion}.py" if companion and output.parent / f"{companion}.py" in published else None,
        tasks_package=output.parent / tasks_package if tasks_package and output.parent / tasks_package in published else None,
        python_tasks=len(emitted),
        python_candidates=candidates,
        image_id_tasks=sum(1 for e in emitted.values() if e.task.image_id is not None),
        unwrap_tasks=sum(1 for e in emitted.values() if e.task.unwrap),
        digest_refs=len(digests),
    )


def _verified_digests(sidecar: Path, sidecar_name: str, converted: set[str]) -> dict[str, str]:
    """sidecar URL -> published digest, for every fragment whose only entries
    are a library-verified digest and its local copy (the dehydrator writes the
    digest only once the library returned that spec)."""
    import yaml

    if not sidecar.is_file():
        return {}
    digests = {}
    for fragment, entries in (yaml.safe_load(sidecar.read_text(encoding="utf-8")) or {}).items():
        url = f"resolve://./{sidecar_name}#{fragment}"
        if (
            url not in converted
            and isinstance(entries, list)
            and len(entries) == 2
            and isinstance(entries[0], Mapping)
            and set(entries[0]) == {"digest", "fallback_on_error"}
            and isinstance(entries[0]["digest"], str)
            and isinstance(entries[1], Mapping)
            and set(entries[1]) == {"local"}
        ):
            digests[url] = entries[0]["digest"]
    return digests


def _count_python_candidates(canonical: CanonicalComponents) -> int:
    return len({ref["url"] for _, ref, spec in _paired_leaves(canonical) if _has_python_markers(spec)})


def _recover_python_tasks(canonical: CanonicalComponents) -> tuple[dict[str, _PythonTask], int]:
    """sidecar URL -> recoverable task, and how many leaves carry the markers."""
    recovered: dict[str, _PythonTask] = {}
    for _, ref, spec in _paired_leaves(canonical):
        task = _python_task(spec)
        if task is not None:
            recovered[ref["url"]] = task
    return recovered, _count_python_candidates(canonical)


def _paired_leaves(canonical: CanonicalComponents) -> Iterator[tuple[tuple[str, ...], Mapping[str, Any], Any]]:
    """Each pinned leaf ref with the resolved spec it was pinned from."""
    specs = {path: ref.get("spec") for path, ref in _pinned_locators(canonical.hydrated)}
    for path, ref in _pinned_locators(canonical.pinned):
        if isinstance(ref.get("url"), str):
            yield path, ref, specs.get(path)


def _prune_sidecar(stage: Path, sidecar_name: str, converted: set[str]) -> None:
    """Drop the fragments, and local copies, only converted leaves used."""
    import yaml

    from .utils import dump_yaml

    prefix = f"resolve://./{sidecar_name}#"
    sidecar = stage / sidecar_name
    manifest = yaml.safe_load(sidecar.read_text(encoding="utf-8")) or {}
    kept = {k: v for k, v in manifest.items() if f"{prefix}{k}" not in converted}
    local = {
        str(PurePosixPath(entry["local"]))
        for entries in kept.values()
        for entry in entries
        if isinstance(entry, Mapping) and isinstance(entry.get("local"), str)
    }
    assets = stage / sidecar_name[: -len(".yaml")]
    for path in sorted(assets.rglob("*"), reverse=True) if assets.is_dir() else ():
        if path.is_file() and path.relative_to(stage).as_posix() not in local:
            path.unlink()
        elif path.is_dir() and not any(path.iterdir()):
            path.rmdir()
    if kept:
        sidecar.write_text(dump_yaml(kept), encoding="utf-8")
    else:
        sidecar.unlink()


def _ref_url(node: ast.AST) -> str | None:
    """The literal URL of a generated ``ref(url=...)`` call, else None."""
    if (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == "ref"
        and not node.args
        and len(node.keywords) == 1
        and node.keywords[0].arg == "url"
        and isinstance(node.keywords[0].value, ast.Constant)
        and isinstance(node.keywords[0].value.value, str)
    ):
        return node.keywords[0].value.value
    return None


def _assert_remaining_leaves_resolve(stage: Path, sidecar_name: str, sources: Sequence[str]) -> None:
    """Every YAML leaf left in the generated code names a fragment that is
    still defined, whose local copies are all still there."""
    import yaml

    prefix = f"resolve://./{sidecar_name}#"
    sidecar = stage / sidecar_name
    manifest = (yaml.safe_load(sidecar.read_text(encoding="utf-8")) or {}) if sidecar.is_file() else {}
    for source in sources:
        for node in ast.walk(ast.parse(source)) if source else ():
            # Only generated ``ref(url=...)`` locators: the same text in an
            # argument, default or annotation is user data, not a reference.
            url = _ref_url(node)
            if url is not None and url.startswith(prefix):
                entries = manifest.get(url[len(prefix):])
                if not entries or not all(
                    (stage / entry["local"]).is_file() for entry in entries if isinstance(entry, Mapping) and "local" in entry
                ):
                    raise DecompileError(
                        "pinning-incomplete",
                        "removing the converted Python components from the sidecar "
                        "left a YAML leaf without its pinned copy.",
                    )


@contextlib.contextmanager
def _staging_directory(parent: Path) -> Iterator[Path]:
    """A scratch directory beside the destination, always cleaned up.

    Beside the destination rather than in the system temp area so that
    publication is a rename within one filesystem.
    """
    parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix=".decompile-", dir=parent))
    try:
        yield stage
    finally:
        shutil.rmtree(stage, ignore_errors=True)


def _publish(
    staged_script: Path, script: Path, sidecars: list[tuple[Path, Path]]
) -> list[Path]:
    """Move the staged script and its sidecars into place as one transaction.

    POSIX offers no multi-path atomic rename, so the guarantee is that
    everything fallible -- resolution, pinning, codegen and both gates -- has
    already happened, and that a rename which fails anyway is rolled back
    across EVERY product: the previous script keeps the resolve config and
    components it was published with. Previous sidecars are moved aside, not
    deleted, until the script rename -- always last -- has succeeded; one the
    new run no longer needs is removed then, never merged into.

    ``sidecars`` are ``(staged, destination)`` pairs, files or directories.
    Returns the destinations actually published.
    """
    sidelined: list[tuple[Path, Path]] = []
    placed: list[tuple[Path, Path]] = []
    try:
        for staged, destination in sidecars:
            if destination.exists() or destination.is_symlink():
                aside = destination.with_name(f"{destination.name}.replaced-{os.getpid()}")
                os.replace(destination, aside)
                sidelined.append((destination, aside))
            wanted = staged.is_file() or (staged.is_dir() and any(staged.iterdir()))
            if wanted:
                os.replace(staged, destination)
                placed.append((staged, destination))
        os.replace(staged_script, script)
    except OSError:
        # Undo newest-first so a failed publication leaves the previous
        # generation together, not mismatched.
        for staged, destination in reversed(placed):
            os.replace(destination, staged)
        for destination, aside in reversed(sidelined):
            os.replace(aside, destination)
        raise

    for _, aside in sidelined:
        if aside.is_dir() and not aside.is_symlink():
            shutil.rmtree(aside, ignore_errors=True)
        else:
            with contextlib.suppress(OSError):
                aside.unlink()
    return [destination for _, destination in placed]


def _parse_input(pipeline_path: Path) -> Any:
    """Read and parse the input, reporting position instead of content.

    A YAML error renders the offending token into its message, and nothing
    in an unparsed file has been validated yet. ``utils.parse_yaml_string``
    is bypassed deliberately: it prints the offending source line and then
    returns ``None``, which would both leak and lose the position.
    """
    import yaml

    try:
        return yaml.safe_load(pipeline_path.read_text(encoding="utf-8"))
    except Exception as exc:
        mark = getattr(exc, "problem_mark", None)
        where = (
            f" at line {mark.line + 1}, column {mark.column + 1}"
            if mark is not None
            else ""
        )
        raise DecompileError(
            "unreadable-input",
            f"{pipeline_path} could not be read as YAML{where}.",
        ) from exc


def assert_supported_input(data: Mapping[str, Any]) -> bool:
    """Validate a hydrated or dehydrated input under its own contract.

    Returns True when the document is hydrated. Classification happens before
    resolution because resolution would otherwise launder an unsupported
    shape -- inlining a spec that was already inline, or dropping a ref's
    sibling keys -- into something a later check would accept.
    """
    document = _require_mapping(data, "pipeline document")
    _refuse_inline_component_text(document)
    if _has_inline_component_spec(document):
        _assert_valid_hydrated_input(document)
        return True
    assert_dehydrated_input(document)
    return False


def _iter_component_refs(document: Mapping[str, Any]) -> Iterator[tuple[str, Mapping[str, Any]]]:
    """Yield ``(path, componentRef)`` for every task at any graph depth."""

    def visit(tasks: Any, prefix: str) -> Iterator[tuple[str, Mapping[str, Any]]]:
        if not isinstance(tasks, Mapping):
            return
        for task_id, body in tasks.items():
            if not isinstance(body, Mapping):
                continue
            where = f"{prefix}{task_id}"
            ref = body.get("componentRef")
            if isinstance(ref, Mapping):
                yield where, ref
                spec = ref.get("spec")
                if isinstance(spec, Mapping):
                    nested = spec.get("implementation")
                    if isinstance(nested, Mapping):
                        graph = nested.get("graph")
                        if isinstance(graph, Mapping):
                            yield from visit(graph.get("tasks"), f"{where}.")

    implementation = document.get("implementation")
    if isinstance(implementation, Mapping):
        graph = implementation.get("graph")
        if isinstance(graph, Mapping):
            yield from visit(graph.get("tasks"), "")


def _has_inline_component_spec(document: Mapping[str, Any]) -> bool:
    return any(isinstance(ref.get("spec"), Mapping) for _, ref in _iter_component_refs(document))


def _refuse_inline_component_text(document: Mapping[str, Any]) -> None:
    """Refuse ``componentRef.text``, which neither contract can represent.

    The general schema still permits it, and hydration drops it silently, so
    accepting it would generate a script missing part of its input.
    """
    # Key presence, not truthiness: an empty `text` is still a legacy key the
    # generated script cannot represent.
    carrying = [where for where, ref in _iter_component_refs(document) if "text" in ref]
    if carrying:
        raise DecompileError(
            "unsupported-document",
            "inline componentRef.text is out of scope for this command; it "
            "cannot be expressed in Python authoring and would be dropped. "
            f"Found at: {', '.join(sorted(carrying))}.",
        )


def _assert_valid_hydrated_input(document: Mapping[str, Any]) -> None:
    """Validate an inline-spec document against the general pipeline schema.

    Uses structured error paths rather than the formatted messages, which
    render the rejected value.
    """
    import jsonschema

    from .pipeline_validation import _should_ignore_schema_error, load_pipeline_schema
    from .schema_validation import (
        SchemaValidationError,
        assert_no_template_delimiters,
    )

    # The general schema permits compile-time templates; this command does
    # not. Checked here rather than downstream so an unrendered template
    # cannot be laundered away by resolution first.
    try:
        assert_no_template_delimiters(document, _runtime_sentinel_paths(document))
    except SchemaValidationError as exc:
        raise DecompileError(
            "unsupported-document",
            "input still contains compile-time template delimiters, which "
            f"are out of scope for this command. {_redacted_validation_reason(exc)}",
        ) from exc

    validator = jsonschema.Draft7Validator(load_pipeline_schema())
    errors = [e for e in validator.iter_errors(document) if not _should_ignore_schema_error(e)]
    if not errors:
        return
    best = min(errors, key=lambda e: list(e.absolute_path))
    location = ".".join(str(p) for p in best.absolute_path) or "root"
    raise DecompileError(
        "unsupported-document",
        "input is not a valid pipeline document. "
        f"The document is invalid at {location}.",
    )


def assert_dehydrated_input(data: Mapping[str, Any]) -> frozenset[str]:
    """Require a dehydrated pipeline document and return its exempt paths.

    Runs before anything else touches the document. Hydration happily inlines
    a spec that was already inline and drops sibling keys such as a ref's
    literal ``text``, so validating only the canonicalized result would let an
    out-of-scope input through and silently discard part of it.
    """
    from .schema_validation import SchemaValidationError, validate_dehydrated_pipeline

    document = _require_mapping(data, "pipeline document")
    exempt_paths = _runtime_sentinel_paths(document)
    try:
        validate_dehydrated_pipeline(document, exempt_paths)
    except SchemaValidationError as exc:
        raise DecompileError(
            "unsupported-document",
            "input is not a valid dehydrated pipeline document. Hydrated "
            "specs, inline component text, legacy keys and compile-time "
            "templates are all out of scope for this command. "
            # Only the location, never the validator's rendering of the
            # offending value: an argument or annotation can hold a secret.
            f"{_redacted_validation_reason(exc)}",
        ) from exc
    return exempt_paths


def _redacted_validation_reason(exc: Exception) -> str:
    """Location of a schema failure with the offending value removed.

    The validator renders the rejected value into its message, which may be a
    secret. The location is read from the exception's structured ``location``
    -- built from the document's own keys -- and the message text is never
    parsed: a rejected value shaped like ``" at something: "`` would
    otherwise be reported as if it were the path.
    """
    location = getattr(exc, "location", None)
    if isinstance(location, str) and location:
        return f"The document is invalid at {location}."
    return "Run `tangle sdk pipelines validate` for the full report."


_CREDENTIAL_IN_URL = re.compile(r"(?P<scheme>[A-Za-z][A-Za-z0-9+.-]*://)[^/\s@]*@")
_URL_QUERY = re.compile(r"(?P<url>[A-Za-z][A-Za-z0-9+.-]*://\S*?)\?\S*")


class _QuietLogger:
    """Drops upstream progress text instead of forwarding it.

    Hydration and dehydration render document content into their own output
    -- locator URLs, and via ``utils.parse_yaml_string`` the offending source
    line of a malformed component -- which this command must not echo. The
    chosen diagnostics carry everything the reader needs.
    """

    def info(self, msg: str) -> None:
        pass

    def warn(self, msg: str) -> None:
        pass

    def error(self, msg: str) -> None:
        pass


def _safe_detail(exc: Exception) -> str:
    """An upstream message with credential-bearing URL parts removed.

    Locators are kept because they are what the reader must fix, but a URL
    can carry userinfo or a signed query, and these messages are built from
    unvalidated document text.
    """
    detail = _CREDENTIAL_IN_URL.sub(r"\g<scheme>[redacted]@", str(exc))
    return _URL_QUERY.sub(r"\g<url>?[redacted]", detail)


# The resolver kinds decompile may use: each only reads a file or the network.
# They are pinned to the built-in implementations, so a downstream
# re-registration cannot swap code in. EVERY other kind -- local_from_python,
# the docker/container spellings, anything a downstream package registers --
# is refused, never run, and a kind no one registered is already refused by
# the hydrator itself: a new resolver kind fails closed until it is listed here.
_STATIC_RESOLVER_KINDS = {
    "digest": "_resolve_digest",
    "name": "_resolve_name",
    "url": "_resolve_url",
    "file": "_resolve_file",
    "resolve": "_resolve_resolve",
    "http": "_resolve_http",
    "https": "_resolve_http",
    "local": "_resolve_local",
}


_STATIC_URI_READERS = {"http": "_read_http_uri", "https": "_read_http_uri"}


class _StaticResolution:
    """Resolver overrides for every decompiler hydrator, whatever the cwd or
    ``--trusted-source`` trust. Refusals are recorded, so the code stays
    stable even where a ``fallback_on_error`` entry swallows the error."""

    def __init__(self) -> None:
        self.refused: DecompileError | None = None

    def resolvers(self) -> dict[str, Any]:
        from . import pipeline_hydrator as hydrator_module

        # The hydrator's own list of resolve-entry kinds, so a spelling it
        # learns later is refused here too.
        known = hydrator_module.PipelineHydrator._resolve_entry_kinds(_KindsOnly())  # type: ignore[arg-type]
        overrides: dict[str, Any] = {kind: self._refusal(kind) for kind in {*hydrator_module.COMPONENT_RESOLVERS, *known}}
        overrides.update({kind: getattr(hydrator_module, name) for kind, name in _STATIC_RESOLVER_KINDS.items()})
        return overrides

    def uri_readers(self) -> dict[str, Any]:
        """The same rule for URI schemes: only the built-in network readers,
        pinned; every other registered reader is refused, never called."""
        from . import pipeline_hydrator as hydrator_module

        overrides: dict[str, Any] = {scheme: self._refusal(scheme) for scheme in hydrator_module.URI_READERS}
        overrides.update({scheme: getattr(hydrator_module, name) for scheme, name in _STATIC_URI_READERS.items()})
        return overrides

    def _refusal(self, kind: str) -> Any:
        error = _LOCAL_PYTHON if kind == "local_from_python" else _EXECUTABLE_SOURCE

        def refuse(*_: Any) -> Any:
            self.refused = error
            raise error

        return refuse

    def check(self) -> None:
        if self.refused is not None:
            raise self.refused


class _KindsOnly:
    component_resolvers: dict[str, Any] = {}


def _static_hydrator(guard: _StaticResolution, **options: Any) -> Any:
    """A hydrator that resolves without running anything.

    Besides the resolver allowlist, a local file or fallback copy may be a
    ``template_file`` config, which the hydrator renders with full Jinja --
    able to reach Python builtins -- so rendering is refused too. Decompiler
    only: the shared hydrator keeps rendering for ``pipelines hydrate``.
    """
    from .pipeline_hydrator import PipelineHydrator

    class _StaticHydrator(PipelineHydrator):
        def _render_template_config(self, *args: Any, **kwargs: Any) -> Any:
            guard.refused = _TEMPLATE_SOURCE
            raise _TEMPLATE_SOURCE

    return _StaticHydrator(component_resolvers=guard.resolvers(), uri_readers=guard.uri_readers(), **options)


_HYDRATE_FIRST = (
    "Run `tangle sdk pipelines hydrate` on it first -- that is where trusted "
    "sources are executed -- then decompile the hydrated YAML."
)
_LOCAL_PYTHON = DecompileError(
    "unsupported-local-python-source",
    "this pipeline references a local Python component (local_from_python), "
    f"and resolving it would run that source; decompile never does. {_HYDRATE_FIRST}",
)
_TEMPLATE_SOURCE = DecompileError(
    "unsupported-template-component-source",
    "this pipeline references a template_file component config, and rendering "
    f"it would evaluate a Jinja template; decompile never does. {_HYDRATE_FIRST}",
)
_EXECUTABLE_SOURCE = DecompileError(
    "unsupported-executable-component-source",
    "this pipeline references a component whose resolver may build or run "
    f"code (anything but a digest, name, URL or file); decompile never does. {_HYDRATE_FIRST}",
)


def canonicalize_components(
    document: Mapping[str, Any],
    *,
    base_dir: Path | None,
    components_dir: Path,
    output_file: Path,
    client: Any = None,
    sidecar_name: str | None = None,
) -> CanonicalComponents:
    """Resolve every componentRef, then re-pin it through a resolve sidecar.

    Hydration inlines each spec; the shared DIGEST dehydration contract then
    puts every task on ``resolve://./<stem>.components.yaml#<fragment>`` (or
    ``sidecar_name``, beside it), whose entries are a verified published digest
    (when there is one) followed by a local copy extracted into ``components_dir``.

    Any failure aborts the whole operation. The hydrator raises for a single
    reference it cannot resolve, but a ref carrying several locators falls back
    to the first one and returns unresolved instead, so the post-check between
    the two stages is what stops that case from being re-emitted silently.
    """
    from .pipeline_dehydrator import DehydrateChoice, PipelineDehydrator
    from .pipeline_hydrator import HydrationError

    # Seed-time exactness: resolve the exact referenced content. Following a
    # deprecation successor here would seed a different component than the
    # input names; later hydrate/submit/run still upgrade as usual.
    guard = _StaticResolution()
    hydrator = _static_hydrator(guard, client=client, logger=_QuietLogger(), upgrade_deprecated=False)
    try:
        hydrated = hydrator.resolve_components(
            copy.deepcopy(dict(document)), base_dir
        )
    except DecompileError:
        raise
    except HydrationError as exc:
        guard.check()
        # The hydrator located no content for a reference: a missing file or a
        # component the library does not have. Distinguished from the failure
        # below because the fix is the document, not the environment.
        raise DecompileError("unresolved-component", _safe_detail(exc)) from exc
    except RecursionError as exc:
        guard.check()
        # The hydrator has no cycle guard of its own, so a component that
        # (transitively) references itself recurses until Python stops it.
        raise DecompileError(
            "cyclic-component-reference",
            "resolving this pipeline's components recursed without end: its "
            "component references form a cycle, which no pipeline can express.",
        ) from exc
    except Exception as exc:
        guard.check()
        raise DecompileError(
            "component-resolution-failed",
            "could not reach the component library to resolve this pipeline's "
            f"references ({type(exc).__name__}): {_safe_detail(exc)}",
        ) from exc

    guard.check()
    _assert_every_component_resolved(hydrated)

    # Leaves only: every nested graph stays inline so codegen can turn it into
    # a Python @pipeline, while the components inside it are pinned in place.
    dehydrator = PipelineDehydrator(
        {"": DehydrateChoice.DIGEST},
        extract_subgraphs=False,
        components_dir=components_dir,
        output_file=output_file,
        client=client,
        interactive=False,
        logger=_QuietLogger(),
    )
    try:
        pinned = dehydrator.dehydrate(hydrated)
    except Exception as exc:
        raise DecompileError(
            "component-pinning-failed",
            "could not pin the pipeline's resolved components: "
            f"{_safe_detail(exc)}",
        ) from exc
    if sidecar_name is not None:
        _rename_sidecar(pinned, output_file, sidecar_name)
    return CanonicalComponents(hydrated=hydrated, pinned=pinned)


def _rename_sidecar(pinned: Mapping[str, Any], output_file: Path, sidecar_name: str) -> None:
    """Move the dehydrator's ``<stem>.components.yaml`` and retarget every leaf.

    Gate (a) runs afterwards, against the renamed sidecar, so a missed
    reference fails as ``pinning-incomplete`` rather than shipping.
    """
    written = output_file.with_name(f"{output_file.stem}.components.yaml")
    if written.is_file():
        os.replace(written, output_file.with_name(sidecar_name))
    old, new = f"resolve://./{written.name}#", f"resolve://./{sidecar_name}#"
    for _, ref in _pinned_locators(pinned):
        url = ref.get("url")
        if isinstance(url, str) and url.startswith(old):
            ref["url"] = new + url[len(old):]


def _assert_every_component_resolved(document: Mapping[str, Any]) -> None:
    """Refuse the whole document if any componentRef lacks a resolved spec."""

    unresolved: list[str] = []

    def visit(tasks: Any, prefix: str) -> None:
        if not isinstance(tasks, Mapping):
            return
        for task_id, body in tasks.items():
            if not isinstance(body, Mapping):
                continue
            where = f"{prefix}{task_id}"
            ref = body.get("componentRef")
            if isinstance(ref, Mapping):
                spec = ref.get("spec")
                if not isinstance(spec, Mapping) or not spec:
                    unresolved.append(where)
                else:
                    visit(
                        spec.get("implementation", {}).get("graph", {}).get("tasks"),
                        f"{where}/",
                    )

    visit(document.get("implementation", {}).get("graph", {}).get("tasks"), "")
    if unresolved:
        listed = ", ".join(sorted(unresolved))
        raise DecompileError(
            "unresolved-component",
            "every component must resolve before a pipeline can be pinned; "
            f"these did not: {listed}. Check the component library credentials "
            "and that any file:// references exist relative to the input.",
        )


def assert_pinning_preserved(
    canonical: CanonicalComponents, *, script_dir: Path, sidecar: str, client: Any = None
) -> None:
    """Gate (a): the pinned document still denotes the hydrated pipeline.

    Resolves the pinned document the way a consumer would -- from the
    generated script's own directory -- and requires the result to carry the
    same component specs hydration produced. Locators are stripped before
    comparison because they legitimately differ: an extracted file is sorted
    YAML, so its text digest is not the original's.

    This is the only oracle that survives pinning. Once a task is on a bare
    digest the generated Python no longer mentions the component's contents,
    so gate (b) alone cannot tell a correct pin from a wrong one.
    """

    guard = _StaticResolution()
    try:
        rehydrated = _static_hydrator(
            guard, client=client, logger=_QuietLogger(), upgrade_deprecated=False
        ).resolve_components(copy.deepcopy(canonical.pinned), script_dir)
    except Exception as exc:
        guard.check()
        raise DecompileError(
            "pinning-unresolvable",
            "the pinned document could not be resolved back from the "
            f"generated script's directory: {_safe_detail(exc)}",
        ) from exc

    guard.check()
    # No resolution re-check here: an unresolved ref reduces to a null spec,
    # which the comparison below already fails on.
    before = _specs_only(canonical.hydrated)
    after = _specs_only(rehydrated)
    if before != after:
        raise DecompileError(
            "pinning-content-mismatch",
            "pinning changed what the pipeline resolves to. "
            f"{_shape_difference(before, after)}",
        )

    _assert_local_fallback_is_complete(canonical.pinned, before, script_dir)
    _assert_sidecar_locators(canonical.pinned, script_dir, sidecar)


class _UnreachableLibrary:
    """A component library that is down: every remote lookup raises.

    Generated primaries are ``fallback_on_error``, so under this client each one
    falls through to its local copy -- which a healthy primary would otherwise
    short-circuit, leaving the copy the script needs offline never checked.
    """

    def _unreachable(self, *args: Any, **kwargs: Any) -> Any:
        raise ConnectionError("component library deliberately unreachable")

    resolve_digest = get_component_spec = _unreachable
    find_existing_components = list_published_component_infos = _unreachable


def _assert_local_fallback_is_complete(pinned: Mapping[str, Any], expected: Any, script_dir: Path) -> None:
    """Gate (a), offline: the local copies alone must reproduce the pipeline.

    Runs in addition to the online pass, never instead of it: a healthy remote
    primary short-circuits that pass, so it never reads the local copies.
    """

    guard = _StaticResolution()
    try:
        # upgrade_deprecated is moot with no library, but stated for intent.
        offline = _static_hydrator(
            guard, client=_UnreachableLibrary(), logger=_QuietLogger(), upgrade_deprecated=False
        ).resolve_components(
            copy.deepcopy(dict(pinned)), script_dir
        )
    except Exception as exc:
        guard.check()
        raise DecompileError(
            "pinning-incomplete",
            "the local fallback copies could not be resolved with the component "
            "library unreachable, so the generated script would not work offline: "
            f"{_safe_detail(exc)}",
        ) from exc
    guard.check()
    # A missing copy never gets here: a generated ref has one locator, so the
    # hydrator raises for it above rather than leaving a null spec.
    actual = _specs_only(offline)
    if actual != expected:
        raise DecompileError(
            "pinning-content-mismatch",
            "a local fallback copy resolves to different content than the "
            f"pipeline, so the script would change meaning offline. {_shape_difference(expected, actual)}",
        )


def _assert_sidecar_locators(pinned: Mapping[str, Any], script_dir: Path, sidecar: str) -> None:
    """Every task must use the generated sidecar, and it must stay portable.

    Accepts only ``resolve://./<sidecar>#<fragment>`` naming a fragment the
    sidecar defines, whose entries are a published digest or a local copy
    inside ``<stem>.leaves/``. Anything else -- an absolute or traversing
    path, a foreign manifest, a mutable URL -- would not survive moving the
    generated script, or would resolve to something gate (a) never checked.
    """
    import yaml

    prefix = f"resolve://./{sidecar}#"
    assets = sidecar[: -len(".yaml")]
    manifest_path = script_dir / sidecar
    manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8")) if manifest_path.is_file() else {}
    if not isinstance(manifest, Mapping):
        manifest = {}

    for path, ref in _pinned_locators(pinned):
        where = "/".join(path)
        url = ref.get("url") if set(ref) == {"url"} else None
        fragment = url[len(prefix):] if isinstance(url, str) and url.startswith(prefix) else None
        # A fragment the sidecar does not define never gets here: resolving the
        # pinned document through this same sidecar has already failed.
        if not fragment:
            raise DecompileError(
                "pinning-incomplete",
                f"task {where} is not pinned through the generated {sidecar} "
                "sidecar, so it would not survive moving the generated script.",
            )
        for entry in manifest.get(fragment) or ():
            if not _portable_sidecar_entry(entry, assets):
                raise DecompileError(
                    "pinning-incomplete",
                    f"task {where} resolves through a sidecar entry that is not a "
                    f"published digest or a local copy inside {assets}/.",
                )


def _portable_sidecar_entry(entry: Any, assets: str) -> bool:
    if not isinstance(entry, Mapping):
        return False
    if set(entry) <= {"digest", "fallback_on_error"} and isinstance(entry.get("digest"), str):
        return True
    local = entry.get("local")
    if set(entry) != {"local"} or not isinstance(local, str) or not local.startswith("./"):
        return False
    parts = PurePosixPath(local[2:]).parts
    return len(parts) >= 2 and parts[0] == assets and ".." not in parts


def _specs_only(document: Any) -> Any:
    """``document`` with every componentRef reduced to its resolved spec."""

    if isinstance(document, Mapping):
        out = {}
        for key, value in document.items():
            if key == "componentRef" and isinstance(value, Mapping):
                out[key] = {"spec": _specs_only(value.get("spec"))}
            else:
                out[key] = _specs_only(value)
        return out
    if isinstance(document, list):
        return [_specs_only(item) for item in document]
    return document


def _pinned_locators(document: Mapping[str, Any], path: tuple[str, ...] = ()) -> Iterator[tuple[tuple[str, ...], Any]]:
    """Every leaf componentRef at every depth, with its task-id path.

    An inline graph boundary is not a locator -- it becomes a Python
    subpipeline -- but the leaves inside it are, and must be portable too.
    Paths are tuples, never joined keys: task ids may contain ``/``, so a
    root ``a/b`` and a nested ``a`` -> ``b`` must not collapse into one.
    """
    tasks = document.get("implementation", {}).get("graph", {}).get("tasks")
    if not isinstance(tasks, Mapping):
        return
    for task_id, body in tasks.items():
        ref = body.get("componentRef") if isinstance(body, Mapping) else None
        if not isinstance(ref, Mapping):
            continue
        if _is_graph_spec(ref.get("spec")):
            yield from _pinned_locators(ref["spec"], (*path, str(task_id)))
        else:
            yield (*path, str(task_id)), ref


def _is_graph_spec(spec: Any) -> bool:
    return isinstance(spec, Mapping) and isinstance(spec.get("implementation"), Mapping) and "graph" in spec["implementation"]


