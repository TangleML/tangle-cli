def _verify_round_trip(
    source: str, original: Mapping[str, Any], pipeline_name: str
) -> None:
    """Recompile the generated source and require semantic identity.

    Uses trace+emit rather than the full compile driver: the driver's
    asset policy resolves relative ``file://`` and ``resolve://`` refs
    against the output directory, which most corpus documents would fail
    purely because the referenced files are not beside a temp directory.
    """
    with tempfile.TemporaryDirectory() as tmp:
        module_path = Path(tmp) / "decompiled_pipeline.py"
        module_path.write_text(source, encoding="utf-8")
        rebuilt, exempt_paths, _ = _trace_function(module_path, None)
    _compare_rebuilt(rebuilt, exempt_paths, original)


def _trace_function(module_path: Path, function_name: str | None) -> tuple[dict[str, Any], Any, list[tuple[str, str]]]:
    """Trace+emit one ``@pipeline`` function; also return its subpipeline calls."""
    from .python_pipeline import emit, trace
    from .python_pipeline.cfg import Cfg
    from .python_pipeline.errors import CompileError

    try:
        with _scrubbed_config_environment():
            from .pipeline_compiler import _load_pipeline_fn

            pipeline_fn = _load_pipeline_fn(module_path, function_name)
            builder = trace.trace_pipeline(pipeline_fn, cfg=Cfg({}), inputs={})
            rebuilt, exempt_paths = emit.emit_pipeline(builder)
    except CompileError as exc:
        raise DecompileError(
            "verification-compile-failed",
            "the generated source did not compile back to a pipeline: "
            f"{_safe_detail(exc)}",
        ) from exc
    calls = [(str(task_id), ref.child.fn.__name__) for task_id, ref in builder.task_refs_for_subpipelines]
    return rebuilt, exempt_paths, calls


def _compare_rebuilt(rebuilt: dict[str, Any], exempt_paths: Any, original: Mapping[str, Any]) -> None:
    from .schema_validation import SchemaValidationError, validate_dehydrated_pipeline

    try:
        validate_dehydrated_pipeline(rebuilt, exempt_paths)
    except SchemaValidationError as exc:
        raise DecompileError(
            "verification-invalid-output",
            "the recompiled pipeline failed dehydrated validation. "
            f"{_redacted_validation_reason(exc)}",
        ) from exc

    normalized_original = _normalize_for_comparison(original)
    normalized_rebuilt = _normalize_for_comparison(rebuilt)
    expected = compute_spec_digest(normalized_original)
    actual = compute_spec_digest(normalized_rebuilt)
    if expected != actual:
        raise DecompileError(
            "verification-digest-mismatch",
            "the recompiled pipeline is not semantically identical to the "
            f"input (expected digest {expected}, got {actual}). "
            # Diff the NORMALIZED documents: diffing the raw ones reports
            # every N1/N2 difference as a discrepancy and buries the real
            # one in noise.
            f"{_shape_difference(normalized_original, normalized_rebuilt)}",
        )


def _normalize_for_comparison(document: Mapping[str, Any]) -> dict[str, Any]:
    """Apply the one documented comparator normalization, N1.

    N1: a graph input carrying ``default`` but no explicit ``optional``
    compares as ``optional: true``. ``graph_input()`` always writes
    ``optional`` alongside a ``default``, so the key reappears on the
    round trip; the two documents mean the same thing. This is a
    comparator rule only -- it never edits generated source or output.
    """
    normalized = _deep_copy(document)
    for entry in normalized.get("inputs", []) or []:
        if isinstance(entry, dict) and "default" in entry and "optional" not in entry:
            entry["optional"] = True

    # N2: drop vacuous empty blocks, at KNOWN optional locations only. A
    # blanket "drop every empty container" would also hide real loss
    # somewhere the emitter should have written content, so each location
    # is named.
    _drop_if_vacuous(normalized, ("metadata", "labels"))
    _drop_if_vacuous(normalized, ("metadata", "annotations"))
    _drop_if_vacuous(normalized, ("metadata",))
    _drop_if_vacuous(normalized, ("inputs",))
    _drop_if_vacuous(normalized, ("outputs",))

    graph = _graph_of(normalized)
    if graph is not None:
        _drop_if_vacuous(graph, ("outputValues",))
        tasks = graph.get("tasks")
        if isinstance(tasks, Mapping):
            for body in tasks.values():
                if isinstance(body, dict):
                    _drop_if_vacuous(body, ("annotations",))
                    _drop_if_vacuous(body, ("arguments",))
                    _drop_if_vacuous(body, ("executionOptions",))
        _drop_if_vacuous(graph, ("tasks",))
    return normalized


def _drop_if_vacuous(container: Any, path: tuple[str, ...]) -> None:
    """Remove ``path`` from ``container`` when it holds nothing at all.

    ``None``, ``{}`` and ``[]`` all mean "declares nothing" here, and the
    authoring API writes no key in that case.
    """
    for key in path[:-1]:
        container = container.get(key) if isinstance(container, dict) else None
        if container is None:
            return
    if not isinstance(container, dict):
        return
    leaf = path[-1]
    if leaf in container and not container[leaf]:
        container.pop(leaf)


def _graph_of(document: Any) -> dict[str, Any] | None:
    implementation = document.get("implementation") if isinstance(
        document, Mapping
    ) else None
    if not isinstance(implementation, dict):
        return None
    graph = implementation.get("graph")
    return graph if isinstance(graph, dict) else None


def _shape_difference(original: Mapping[str, Any], rebuilt: Mapping[str, Any]) -> str:
    """Describe *where* two documents diverge without echoing any value."""
    original_paths = set(_value_paths(original))
    rebuilt_paths = set(_value_paths(rebuilt))
    missing = sorted(original_paths - rebuilt_paths)[:5]
    added = sorted(rebuilt_paths - original_paths)[:5]
    if not missing and not added:
        return "Key sets match, so at least one value differs."
    parts = []
    if missing:
        parts.append(f"missing from output: {', '.join(missing)}")
    if added:
        parts.append(f"added by output: {', '.join(added)}")
    return "; ".join(parts) + "."


def _value_paths(value: Any, prefix: str = "") -> Iterable[str]:
    if isinstance(value, Mapping):
        for key, child in value.items():
            path = f"{prefix}.{key}" if prefix else str(key)
            yield path
            yield from _value_paths(child, path)
    elif isinstance(value, list):
        for index, child in enumerate(value):
            yield from _value_paths(child, f"{prefix}[{index}]")


def _deep_copy(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {k: _deep_copy(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_deep_copy(v) for v in value]
    return value


@contextlib.contextmanager
def _scrubbed_config_environment() -> Any:
    """Hide ambient config from the verification trace.

    ``TANGLE_ROOT_CONFIG`` would let a developer's local config bind
    ``cfg`` values into the traced graph, so verification could pass or
    fail based on the machine it ran on. Generated source never emits
    ``cfg``, so the variable can only distort the result.
    """
    saved = os.environ.pop("TANGLE_ROOT_CONFIG", None)
    try:
        yield
    finally:
        if saved is not None:
            os.environ["TANGLE_ROOT_CONFIG"] = saved


