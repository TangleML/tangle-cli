# Ordering and naming


def _topological_order(
    raw_tasks: Mapping[str, Any],
) -> list[tuple[str, dict[str, Any]]]:
    """Order tasks so every producer precedes its consumers.

    Python source is sequential, so a task must be assigned to a variable
    before another task can reference it. Ties keep the document's own
    order, which makes an already-topological input round-trip unchanged
    and makes the output a pure function of the input.
    """
    tasks = {str(k): _require_mapping(v, f"task {k!r}") for k, v in raw_tasks.items()}
    position = {task_id: index for index, task_id in enumerate(tasks)}

    dependencies: dict[str, set[str]] = {}
    for task_id, body in tasks.items():
        deps = {
            producer
            for producer in _referenced_task_ids(body)
            if producer in tasks and producer != task_id
        }
        dependencies[task_id] = deps

    ordered: list[tuple[str, dict[str, Any]]] = []
    emitted: set[str] = set()
    remaining = set(tasks)
    while remaining:
        ready = min(
            (t for t in remaining if dependencies[t] <= emitted),
            key=lambda t: position[t],
            default=None,
        )
        if ready is None:
            raise DecompileError(
                "unsupported-task-graph",
                "the task graph contains a cycle, so no sequential Python "
                "source can express it.",
            )
        # One task per round, not the whole ready batch: emitting the batch
        # would put an independent later task ahead of a dependent earlier
        # one, reordering input that was already topological.
        ordered.append((ready, dict(tasks[ready])))
        emitted.add(ready)
        remaining.discard(ready)
    return ordered


def _referenced_task_ids(body: Mapping[str, Any]) -> set[str]:
    found: set[str] = set()
    candidates: list[Any] = list(
        _require_mapping(body.get("arguments") or {}, "arguments").values()
    )
    if "isEnabled" in body:
        candidates.append(body["isEnabled"])
    for value in candidates:
        if isinstance(value, Mapping) and isinstance(
            value.get("taskOutput"), Mapping
        ):
            task_id = value["taskOutput"].get("taskId")
            if isinstance(task_id, str):
                found.add(task_id)
    return found


def _ascii_words(value: str) -> list[str]:
    normalized = (
        unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode("ascii")
    )
    return [part.lower() for part in re.findall(r"[A-Za-z0-9]+", normalized)]


def _python_identifier(value: str, *, prefix: str) -> str:
    """Port of the Airflow converter's identifier rule.

    Ported rather than imported: that module lives downstream in
    tangle-deploy, and this package must not depend on it.
    """
    candidate = "_".join(_ascii_words(value)) or prefix
    if candidate[0].isdigit():
        candidate = f"{prefix}_{candidate}"
    # Builtins as well as keywords: a module-level ``def getattr(...)`` shadows
    # the builtin for the whole module, and the emitter uses ``getattr`` to
    # reach outputs whose names are not identifiers.
    if (
        keyword.iskeyword(candidate)
        or candidate in _IMPORTS
        or candidate == "subpipeline"
        or hasattr(builtins, candidate)
    ):
        candidate = f"{candidate}_"
    return candidate


def _allocate_names(
    input_names: Sequence[str], task_ids: Sequence[str]
) -> dict[str, str]:
    """Allocate one flat namespace for graph inputs and tasks.

    Inputs and tasks share the function body's local scope, so they are
    allocated together: ``"Foo"`` as both an input name and a task id must
    not collapse onto one variable. Keys are prefixed by kind so the two
    namespaces stay distinguishable in the returned map.
    """
    allocated: set[str] = set(_IMPORTS)
    result: dict[str, str] = {}
    for kind, values, prefix in (
        ("input", input_names, "input"),
        ("task", task_ids, "task"),
    ):
        for value in values:
            base = f"{prefix}_{_python_identifier(value, prefix=prefix)}"
            candidate = base
            attempt = 0
            while candidate in allocated:
                attempt += 1
                digest = hashlib.sha256(
                    f"{value}:{attempt}".encode("utf-8")
                ).hexdigest()[:8]
                candidate = f"{base}_{digest}"
            allocated.add(candidate)
            result[f"{kind}:{value}"] = candidate
    return result


