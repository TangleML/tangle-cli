class DecompileError(Exception):
    """A dehydrated document this decompiler refuses to represent.

    Carries a stable ``code`` so callers can branch on the refusal reason.
    Messages name the construct and its location; they never echo the
    offending value, which may be a secret or a config leak.
    """

    def __init__(self, code: str, message: str) -> None:
        super().__init__(f"[{code}] {message}")
        self.code = code
        self.message = message


