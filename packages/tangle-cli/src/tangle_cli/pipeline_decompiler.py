# Refusals


def _check_input(entry: Any, index: int) -> dict[str, Any]:
    spec = dict(_require_mapping(entry, f"inputs[{index}]"))
    name = spec.get("name")
    if not isinstance(name, str) or not name:
        raise DecompileError(
            "unsupported-document", f"inputs[{index}] has no usable 'name'."
        )
    if "default" in spec and spec["default"] is None:
        raise DecompileError(
            "unsupported-input-default",
            f"graph input {name!r} declares a null default. graph_input() "
            "refuses default=None; omit the key to declare no default.",
        )
    if "value" in spec:
        raise DecompileError(
            "unsupported-input-value",
            f"graph input {name!r} carries a baked 'value', which the "
            "authoring API cannot express.",
        )
    _check_io_annotations(spec, f"graph input {name!r}")
    return spec


def _check_io_annotations(spec: Mapping[str, Any], where: str) -> None:
    """Pre-check what ``CALLER_ANNOTATION_POLICY`` enforces at authoring time.

    graph_input/graph_output annotations run through the caller policy, so
    a non-string value, a reserved ``system/`` prefix or an embedded
    template delimiter would raise deep inside the generated module. Catch
    it here, where the diagnostic can name the YAML location.
    """
    annotations = spec.get("annotations")
    if annotations is None:
        return
    for key, value in _require_mapping(annotations, f"{where} annotations").items():
        if not isinstance(value, str):
            raise DecompileError(
                "unsupported-io-annotations",
                f"{where} annotation {key!r} is {type(value).__name__}; the "
                "authoring API accepts string annotation values only.",
            )
        if str(key).startswith("system/"):
            raise DecompileError(
                "unsupported-io-annotations",
                f"{where} annotation {key!r} uses the reserved 'system/' "
                "prefix, which the authoring API refuses.",
            )


def _check_task(task_id: str, body: Mapping[str, Any]) -> None:
    component_ref = _require_mapping(
        body.get("componentRef") or {}, f"task {task_id!r} componentRef"
    )
    if not any(key in component_ref for key in _LOCATOR_KEYS):
        raise DecompileError(
            "unsupported-component-ref",
            f"task {task_id!r} has a componentRef with no url, name or "
            "digest. Inline and hydrated specs are out of scope.",
        )

    for key, value in _require_mapping(
        body.get("arguments") or {}, f"task {task_id!r} arguments"
    ).items():
        _check_argument(task_id, str(key), value)

    if "isEnabled" in body:
        _check_is_enabled(task_id, body["isEnabled"])

    if "executionOptions" in body:
        _check_execution_options(task_id, body["executionOptions"])


def _check_argument(task_id: str, key: str, value: Any) -> None:
    where = f"task {task_id!r} argument {key!r}"
    if isinstance(value, str):
        return
    if not isinstance(value, Mapping):
        raise DecompileError(
            "unsupported-argument",
            f"{where} is {type(value).__name__}; dehydrated arguments are "
            "strings or a graphInput/taskOutput/dynamicData wrapper.",
        )
    if "taskOutput" in value:
        spec = _require_mapping(value["taskOutput"], where)
        _check_edge_keys(spec, {"taskId", "outputName"}, "taskOutput", where)
        output_name = spec.get("outputName")
        if isinstance(output_name, str) and output_name.startswith("_"):
            raise DecompileError(
                "unsupported-task-output-name",
                f"{where} reads an output whose name starts with '_'. The "
                "task-output proxy treats leading-underscore names as "
                "framework-internal and refuses them.",
            )
        return
    if "graphInput" in value:
        _check_edge_keys(
            _require_mapping(value["graphInput"], where),
            {"inputName"},
            "graphInput",
            where,
        )
        return
    if "dynamicData" in value:
        return
    raise DecompileError(
        "unsupported-argument",
        f"{where} uses an unrecognized argument wrapper.",
    )


def _check_edge_keys(
    spec: Mapping[str, Any], allowed: set[str], kind: str, where: str
) -> None:
    """Refuse an edge wrapper carrying keys the emitter would silently drop.

    ``emit.py`` writes exactly ``{taskId, outputName}`` / ``{inputName}``,
    so an extra key such as a ``graphInput.type`` hint is real data that
    cannot survive. Dropping it quietly would make the round trip lossy in
    a way the digest gate catches but nobody could explain, so it is named
    here instead.
    """
    extra = sorted(set(spec) - allowed)
    if extra:
        raise DecompileError(
            "unsupported-edge-fields",
            f"{where} has a {kind} wrapper carrying {', '.join(extra)}, "
            f"which the authoring API does not model: it emits only "
            f"{', '.join(sorted(allowed))}.",
        )


def _check_is_enabled(task_id: str, value: Any) -> None:
    if isinstance(value, str):
        return
    if isinstance(value, Mapping) and ("taskOutput" in value or "graphInput" in value):
        return
    raise DecompileError(
        "unsupported-is-enabled",
        f"task {task_id!r} has an isEnabled of type "
        f"{type(value).__name__}; only a string, graphInput or taskOutput "
        "is supported.",
    )


def _check_execution_options(task_id: str, value: Any) -> None:
    options = _require_mapping(value, f"task {task_id!r} executionOptions")
    for group, fields in options.items():
        allowed = _EXECUTION_OPTION_FIELDS.get(str(group))
        if allowed is None:
            raise DecompileError(
                "unsupported-execution-options",
                f"task {task_id!r} declares the executionOptions group "
                f"{group!r}, which the backend does not model and would "
                "drop silently.",
            )
        for key in _require_mapping(
            fields, f"task {task_id!r} executionOptions.{group}"
        ):
            if str(key) not in allowed:
                raise DecompileError(
                    "unsupported-execution-options",
                    f"task {task_id!r} declares executionOptions."
                    f"{group}.{key}, which the backend does not model and "
                    "would drop silently.",
                )


