# Codegen (ast only)


def _render(plan: _Plan) -> str:
    return _render_module([plan])


def _render_module(
    plans: list[_Plan], companion: str | None = None, companion_names: tuple[str, ...] = (), tasks_package: str | None = None
) -> str:
    """One module of ``@pipeline`` functions, defined in dependency order.

    ``subpipeline`` is imported only when used, so a document with no nested
    graphs renders exactly as it always has.
    """
    names = list(_IMPORTS)
    if any(plan.subpipelines for plan in plans):
        names = sorted([*names, "subpipeline"])
    body: list[ast.stmt] = [
        ast.ImportFrom(
            module="tangle_cli.python_pipeline",
            names=[ast.alias(name=n, asname=None) for n in names],
            level=0,
        )
    ]
    if companion and companion_names:
        body.append(
            ast.ImportFrom(
                module=companion,
                names=[ast.alias(name=n, asname=None) for n in companion_names],
                level=0,
            )
        )
    task_names = sorted({
        plan.python_tasks[body_["componentRef"]["url"]]
        for plan in plans
        for _, body_ in plan.tasks
        if set(body_.get("componentRef") or {}) == {"url"} and body_["componentRef"]["url"] in plan.python_tasks
    })
    if tasks_package and task_names:
        body.append(
            ast.ImportFrom(module=tasks_package, names=[ast.alias(name=n, asname=None) for n in task_names], level=0)
        )
    body.extend(_pipeline_function(plan) for plan in plans)
    module = ast.Module(body=body, type_ignores=[])
    ast.fix_missing_locations(module)
    rendered = ast.unparse(module)
    header = _HEADER
    if tasks_package and task_names:
        header += (
            f"\nExcept the Python components imported from {tasks_package}: Tangle\n"
            "rebuilds those from their recovered source, which is not proven here.\n"
        )
    return f'"""{header}"""\n{rendered}\n'


def _pipeline_function(plan: _Plan) -> ast.FunctionDef:
    decorator_kwargs = [ast.keyword(arg="name", value=_literal(plan.pipeline_name))]
    if plan.description is not None:
        decorator_kwargs.append(
            ast.keyword(arg="description", value=_literal(plan.description))
        )
    if plan.labels:
        decorator_kwargs.append(ast.keyword(arg="labels", value=_literal(plan.labels)))
    if plan.annotations:
        # Passed as a mapping, never via flow_direction=: that keyword is
        # applied last and would overwrite an authored
        # editor.flow-direction rather than reproduce it.
        decorator_kwargs.append(
            ast.keyword(arg="annotations", value=_literal(plan.annotations))
        )

    statements: list[ast.stmt] = []
    for spec in plan.inputs:
        statements.append(_graph_input_statement(plan, spec))
    for task_id, task_body in plan.tasks:
        statements.append(_task_statement(plan, task_id, task_body))
    for spec in plan.outputs:
        statements.append(_graph_output_statement(plan, spec))
    if not statements:
        statements.append(ast.Pass())

    return ast.FunctionDef(
        name=plan.function_name,
        args=ast.arguments(
            posonlyargs=[],
            args=[],
            vararg=None,
            kwonlyargs=[],
            kw_defaults=[],
            kwarg=None,
            defaults=[],
        ),
        body=statements,
        decorator_list=[
            ast.Call(
                func=ast.Name(id="pipeline", ctx=ast.Load()),
                args=[],
                keywords=decorator_kwargs,
            )
        ],
        returns=ast.Constant(value=None),
        type_comment=None,
    )


def _graph_input_statement(plan: _Plan, spec: Mapping[str, Any]) -> ast.stmt:
    name = str(spec["name"])
    args: list[ast.expr] = [_literal(name)]
    if "type" in spec:
        args.append(_literal(spec["type"]))

    keywords: list[ast.keyword] = []
    if "description" in spec:
        keywords.append(
            ast.keyword(arg="description", value=_literal(spec["description"]))
        )
    if "default" in spec:
        # The original default is already the schema's string form. Passing
        # it verbatim avoids serialize_input_default re-rendering it (True
        # -> "True", dicts -> sorted JSON), which would change the bytes.
        keywords.append(ast.keyword(arg="default", value=_literal(spec["default"])))
    if "optional" in spec:
        keywords.append(ast.keyword(arg="optional", value=_literal(spec["optional"])))
    keywords.extend(_graph_io_annotation_keywords(spec))

    return ast.Assign(
        targets=[ast.Name(id=plan.names[f"input:{name}"], ctx=ast.Store())],
        value=ast.Call(
            func=ast.Name(id="graph_input", ctx=ast.Load()),
            args=args,
            keywords=keywords,
        ),
        type_comment=None,
    )


def _graph_io_annotation_keywords(spec: Mapping[str, Any]) -> list[ast.keyword]:
    """``annotations=`` and, for an exactly reproducible x/y-only
    editor.position, ``position=(x, y)`` -- which graph I/O applies after the
    mapping, so it stays the last write. Anything else (width/height included:
    ``position=`` takes x/y only) stays verbatim in ``annotations=``."""
    annotations = dict(_require_mapping(spec.get("annotations") or {}, "graph I/O annotations"))
    position = _position_sugar(annotations.get(_POSITION_ANNOTATION))
    if position is not None and set(position) != {"x", "y"}:
        position = None
    rest = {k: v for k, v in annotations.items() if k != _POSITION_ANNOTATION} if position else annotations
    keywords = [ast.keyword(arg="annotations", value=_literal(rest))] if rest else []
    if position:
        keywords.append(
            ast.keyword(arg="position", value=ast.Tuple(elts=[_literal(position["x"]), _literal(position["y"])], ctx=ast.Load()))
        )
    return keywords


def _graph_output_statement(plan: _Plan, spec: Mapping[str, Any]) -> ast.stmt:
    name = str(spec["name"])
    edge = plan.output_values.get(name)
    if edge is None:
        raise DecompileError(
            "unsupported-output",
            f"graph output {name!r} has no entry in outputValues; the "
            "authoring API wires every output to a task output or input.",
        )
    args: list[ast.expr] = [_literal(name), _edge_expression(plan, edge, name)]
    if "type" in spec:
        args.append(_literal(spec["type"]))

    keywords: list[ast.keyword] = []
    if "description" in spec:
        keywords.append(
            ast.keyword(arg="description", value=_literal(spec["description"]))
        )
    keywords.extend(_graph_io_annotation_keywords(spec))

    return ast.Expr(
        value=ast.Call(
            func=ast.Name(id="graph_output", ctx=ast.Load()),
            args=args,
            keywords=keywords,
        )
    )


def _task_statement(plan: _Plan, task_id: str, body: Mapping[str, Any]) -> ast.stmt:
    component_ref = _require_mapping(body["componentRef"], "componentRef")
    call: ast.expr
    if task_id in plan.subpipelines:
        call = ast.Call(
            func=ast.Name(id="subpipeline", ctx=ast.Load()),
            args=[ast.Name(id=plan.subpipelines[task_id], ctx=ast.Load())],
            keywords=[],
        )
    elif set(component_ref) == {"url"} and component_ref["url"] in plan.python_tasks:
        call = ast.Name(id=plan.python_tasks[component_ref["url"]], ctx=ast.Load())
    elif set(component_ref) == {"url"} and component_ref["url"] in plan.digest_refs:
        call = _digest_ref(plan.digest_refs[component_ref["url"]])
    else:
        locator_keywords = [
            ast.keyword(arg=key, value=_literal(component_ref[key]))
            for key in _LOCATOR_KEYS
            if key in component_ref
        ]
        call = ast.Call(func=ast.Name(id="ref", ctx=ast.Load()), args=[], keywords=locator_keywords)
    # .named() always: the LHS-derived id is a Title Case transform of the
    # variable name, which cannot reproduce an arbitrary task id.
    call = _method(call, "named", [_literal(task_id)])

    annotations = dict(_require_mapping(body.get("annotations") or {}, "task annotations"))
    position = _position_sugar(annotations.get(_POSITION_ANNOTATION))
    rest = {k: v for k, v in annotations.items() if k != _POSITION_ANNOTATION} if position else annotations
    if rest:
        call = _method(call, "with_annotations", [_literal(rest)])
    if position:
        # Last, so editor.position is its final write whatever else is set.
        call = ast.Call(
            func=ast.Attribute(value=call, attr="with_position", ctx=ast.Load()),
            args=[_literal(position["x"]), _literal(position["y"])],
            keywords=[ast.keyword(arg=k, value=_literal(position[k])) for k in ("width", "height") if k in position],
        )

    arguments = _require_mapping(body.get("arguments") or {}, "arguments")
    bind_pairs: list[tuple[str, ast.expr]] = []
    call_keywords: list[ast.keyword] = []
    task_path = f"implementation.graph.tasks.{task_id}"
    # A recovered @task(unwrap=...) takes each flattened ``<param>__<key>``
    # input back as one ``param={key: ...}`` dict, keys in spec input order,
    # at the position of the first of them.
    converted = set(component_ref) == {"url"} and component_ref["url"] in plan.python_tasks and task_id not in plan.subpipelines
    unwrap = plan.python_unwrap.get(component_ref["url"], {}) if converted else {}
    owner = {f"{name}__{key}": name for name, keys in unwrap.items() for key in keys}
    grouped: set[str] = set()
    for key, value in arguments.items():
        key = str(key)
        if key in owner:
            name = owner[key]
            if name in grouped:
                continue
            grouped.add(name)
            expression = ast.Dict(
                keys=[_literal(k) for k in unwrap[name]],
                values=[
                    _argument_expression(plan, arguments[f"{name}__{k}"], f"{task_path}.arguments.{name}__{k}", task_id, f"{name}__{k}")
                    for k in unwrap[name]
                ],
            )
            key = name
        else:
            expression = _argument_expression(
                plan, value, f"{task_path}.arguments.{key}", task_id, key
            )
        if key in _RESERVED_CALL_KEYWORDS:
            # Would bind the task-metadata parameter instead of the
            # component input; .bind() keeps it an argument.
            bind_pairs.append((key, expression))
        elif key.isidentifier() and not keyword.iskeyword(key):
            call_keywords.append(ast.keyword(arg=key, value=expression))
        else:
            # A **{...} segment at this position keeps the original
            # argument order rather than hoisting odd keys to the end.
            call_keywords.append(
                ast.keyword(
                    arg=None,
                    value=ast.Dict(keys=[_literal(key)], values=[expression]),
                )
            )
    if bind_pairs:
        call = ast.Call(
            func=ast.Attribute(value=call, attr="bind", ctx=ast.Load()),
            args=[],
            keywords=[ast.keyword(arg=k, value=v) for k, v in bind_pairs],
        )

    if "isEnabled" in body:
        call_keywords.append(
            ast.keyword(
                arg="is_enabled",
                value=_is_enabled_expression(plan, body["isEnabled"], task_id),
            )
        )
    execution_options = _require_mapping(
        body.get("executionOptions") or {}, "executionOptions"
    )
    if execution_options:
        # An EMPTY mapping is skipped under N2: the authoring API rejects
        # execution_options={} outright, and the block declares nothing.
        call_keywords.append(
            ast.keyword(
                arg="execution_options", value=_literal(execution_options)
            )
        )

    return ast.Assign(
        targets=[ast.Name(id=plan.names[f"task:{task_id}"], ctx=ast.Store())],
        value=ast.Call(func=call, args=[], keywords=call_keywords),
        type_comment=None,
    )


_POSITION_ANNOTATION = "editor.position"


def _position_sugar(value: Any) -> dict[str, Any] | None:
    """The coordinates ``.with_position`` re-renders to exactly ``value``, or None.

    Only when upstream ``position_annotation_value`` reproduces the very same
    string: a compact, reordered, non-finite, boolean, null or extra-keyed
    payload would be rewritten, so it stays in ``.with_annotations`` verbatim,
    as does one it cannot convert at all (an overlong int, deep nesting).
    """
    import json

    from .editor_layout import position_annotation_value

    if not isinstance(value, str):
        return None
    try:
        position = json.loads(value)
    except (ValueError, RecursionError):
        return None
    if not isinstance(position, dict) or not {"x", "y"} <= set(position) <= {"x", "y", "width", "height"}:
        return None
    try:
        rendered = position_annotation_value(
            position["x"], position["y"], width=position.get("width"), height=position.get("height")
        )
    except (ValueError, OverflowError):  # an int too large for a float
        return None
    return position if rendered == value else None


def _argument_expression(
    plan: _Plan, value: Any, path: str, task_id: str, key: str
) -> ast.expr:
    if isinstance(value, str):
        if path in plan.exempt_paths:
            return ast.Call(
                func=ast.Name(id="raw", ctx=ast.Load()),
                args=[_literal(value)],
                keywords=[],
            )
        return _literal(value)

    mapping = _require_mapping(value, f"task {task_id!r} argument {key!r}")
    if "taskOutput" in mapping or "graphInput" in mapping:
        return _edge_expression(plan, mapping, f"task {task_id!r} argument {key!r}")
    if "dynamicData" in mapping:
        return _dynamic_data_expression(
            mapping["dynamicData"], f"task {task_id!r} argument {key!r}"
        )
    raise DecompileError(
        "unsupported-argument",
        f"task {task_id!r} argument {key!r} uses an unrecognized wrapper.",
    )


def _edge_expression(plan: _Plan, value: Any, where: str) -> ast.expr:
    mapping = _require_mapping(value, where)
    if "taskOutput" in mapping:
        spec = _require_mapping(mapping["taskOutput"], where)
        task_id = str(spec.get("taskId", ""))
        output_name = str(spec.get("outputName", ""))
        variable = plan.names.get(f"task:{task_id}")
        if variable is None:
            raise DecompileError(
                "unsupported-document",
                f"{where} references task {task_id!r}, which the document "
                "does not define.",
            )
        target = ast.Name(id=variable, ctx=ast.Load())
        if (
            output_name.isidentifier()
            and not output_name.startswith("_")
            # A keyword is a valid identifier but not a valid attribute:
            # ``task.class`` does not parse.
            and not keyword.iskeyword(output_name)
        ):
            return ast.Attribute(value=target, attr=output_name, ctx=ast.Load())
        # getattr keeps an arbitrary output name a string literal instead
        # of forcing it through the identifier grammar.
        return ast.Call(
            func=ast.Name(id="getattr", ctx=ast.Load()),
            args=[target, _literal(output_name)],
            keywords=[],
        )
    if "graphInput" in mapping:
        spec = _require_mapping(mapping["graphInput"], where)
        input_name = str(spec.get("inputName", ""))
        variable = plan.names.get(f"input:{input_name}")
        if variable is None:
            raise DecompileError(
                "unsupported-document",
                f"{where} references graph input {input_name!r}, which the "
                "document does not declare.",
            )
        return ast.Name(id=variable, ctx=ast.Load())
    raise DecompileError("unsupported-argument", f"{where} is not a usable edge.")


def _dynamic_data_expression(value: Any, where: str) -> ast.expr:
    mapping = _require_mapping(value, where)
    secret = mapping.get("secret")
    if set(mapping) != {"secret"} or not isinstance(secret, Mapping):
        raise DecompileError(
            "unsupported-dynamic-data",
            f"{where} uses a dynamicData kind other than 'secret'; only "
            "dynamic_secret() exists in the authoring API.",
        )
    secret_name = secret.get("name")
    if set(secret) != {"name"} or not isinstance(secret_name, str) or not secret_name:
        raise DecompileError(
            "unsupported-dynamic-data",
            f"{where} has a dynamicData.secret without a single usable "
            "'name' field.",
        )
    return ast.Call(
        func=ast.Name(id="dynamic_secret", ctx=ast.Load()),
        args=[_literal(secret_name)],
        keywords=[],
    )


def _is_enabled_expression(plan: _Plan, value: Any, task_id: str) -> ast.expr:
    if isinstance(value, str):
        # Emitted as the exact string. A bool would be re-serialized to
        # "true"/"false", which is already what the document holds.
        return _literal(value)
    return _edge_expression(plan, value, f"task {task_id!r} isEnabled")


def _method(value: ast.expr, name: str, args: list[ast.expr]) -> ast.expr:
    return ast.Call(
        func=ast.Attribute(value=value, attr=name, ctx=ast.Load()),
        args=args,
        keywords=[],
    )


def _literal(value: Any) -> ast.expr:
    """Build a literal node for a recovered YAML value.

    Everything reaching generated source goes through here, so no input
    text is ever interpolated: ``ast.unparse`` owns the quoting and
    escaping, which is what makes a hostile name or description inert.
    """
    if isinstance(value, Mapping):
        return ast.Dict(
            keys=[_literal(k) for k in value],
            values=[_literal(v) for v in value.values()],
        )
    if isinstance(value, (list, tuple)):
        return ast.List(elts=[_literal(v) for v in value], ctx=ast.Load())
    if isinstance(value, (str, bool, int, float)) or value is None:
        return ast.Constant(value=value)
    raise DecompileError(
        "unsupported-value",
        f"cannot render a {type(value).__name__} as a Python literal.",
    )


# Node types generated source may legally contain. The generator is the
# only producer, so a node outside this set means a codegen bug, not a
# hostile input -- but the file is about to be imported and executed, so
# it is checked rather than assumed.
_ALLOWED_NODES: tuple[type[ast.AST], ...] = (
    ast.Module,
    ast.ImportFrom,
    ast.alias,
    ast.FunctionDef,
    ast.arguments,
    ast.Assign,
    ast.Expr,
    ast.Pass,
    ast.Call,
    ast.Attribute,
    ast.Name,
    ast.Constant,
    ast.Dict,
    ast.List,
    ast.Tuple,  # graph I/O position=(x, y)
    ast.keyword,
    ast.Load,
    ast.Store,
)


def _is_negative_number(node: ast.UnaryOp) -> bool:
    return (
        isinstance(node.op, ast.USub)
        and isinstance(node.operand, ast.Constant)
        and isinstance(node.operand.value, (int, float))
        and not isinstance(node.operand.value, bool)
    )


def _assert_generated_source_is_safe(source: str, *modules: str | None) -> None:
    """Parse the generated source and allowlist every node in it.

    Imports are pinned too: only the authoring package, plus the generated
    companion and tasks modules when there are any, since this code is about
    to run.
    """
    try:
        tree = ast.parse(source)
    except SyntaxError as exc:  # pragma: no cover - a codegen bug
        raise DecompileError(
            "codegen-syntax-error",
            f"generated source is not valid Python: {exc.msg}",
        ) from exc
    allowed_modules = {"tangle_cli.python_pipeline", *(m for m in modules if m)}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.module not in allowed_modules or node.level):
            raise DecompileError(
                "codegen-unsafe-node",
                "generated source imports an unexpected module. Refusing to "
                "emit code that is about to be executed.",
            )
        if isinstance(node, ast.UnaryOp) and _is_negative_number(node):
            continue  # ast.unparse writes -5 as USub(5)
        if isinstance(node, ast.USub):
            continue
        if not isinstance(node, _ALLOWED_NODES):
            raise DecompileError(
                "codegen-unsafe-node",
                f"generated source contains an unexpected {type(node).__name__} "
                "node. Refusing to emit code that is about to be executed.",
            )


